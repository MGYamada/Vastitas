#!/usr/bin/env python3
"""Build an untracked path package from the canonical flat stdlib sources.

No body rewriting: package mode uses the same arithmetic definitions and the
ordinary namespace checker. Run before package use and after source edits.
--check verifies an existing build without writing files.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "// Generated by scripts/build_stdlib_package.py; edit stdlib/src/arithmetic/.\n"
IMPORTS = """use super::integers::int_add;
use super::integers::int_max;
use super::naturals::nat_add;
use super::naturals::nat_max;

"""


def rendered(name):
    source = (ROOT / "stdlib/src/arithmetic" / f"{name}.vast").read_text()
    public = "\n".join(
        "pub " + line if line.startswith(("fn ", "generic ")) else line
        for line in source.splitlines()
    ) + "\n"
    return HEADER + (IMPORTS if name == "generic" else "") + public


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        "lib.vast": HEADER + "pub mod arithmetic;\n",
        "arithmetic.vast": HEADER + "pub mod integers;\npub mod naturals;\npub mod generic;\n",
    }
    for source, module in [("int", "integers"), ("nat", "naturals"), ("generic", "generic")]:
        outputs[f"arithmetic/{module}.vast"] = rendered(source)
    for name, expected in outputs.items():
        path = ROOT / "stdlib/target/package" / name
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"{path.relative_to(ROOT)} is missing or stale; run python3 scripts/build_stdlib_package.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != expected:
                path.write_text(expected)


if __name__ == "__main__":
    main()
