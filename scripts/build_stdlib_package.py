#!/usr/bin/env python3
"""Build an untracked path package from the canonical flat stdlib sources.

No body rewriting: package mode uses the same arithmetic definitions and the
ordinary namespace checker. Run before package use and after source edits.
--check verifies an existing build without writing files. The entrypoint
re-exports each library package of stdlib/Vastitas.toml under its public name.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = b"// Generated by scripts/build_stdlib_package.py; edit stdlib/src/arithmetic/.\n"
# Dependency alias in stdlib/Vastitas.toml, and its public name under `std`.
# Geometry does not depend on differential; differential depends on geometry.
LIBRARIES = (("geometry_library", "geometry"), ("differential_library", "differential"))
# Each flat source of stdlib/src/arithmetic/, and the module of `std::arithmetic`
# that it becomes. scripts/library_docs.py reads the same outputs.
ARITHMETIC = (("int", "integers"), ("nat", "naturals"), ("generic", "generic"))
IMPORTS = b"""use super::integers::int_add;
use super::integers::int_max;
use super::naturals::nat_add;
use super::naturals::nat_max;

"""


def public(source):
    """The source with `pub` before each line that begins a function or a generic."""
    # LF/CRLF delimit Vastitas lines; other line separators are lexer errors.
    # Universal-newline reading or splitlines() could normalize rejected input
    # into executable source. Preserve the original bytes for the lexer audit.
    return b"\n".join(
        b"pub " + line if line.startswith((b"fn ", b"generic ")) else line
        for line in source.split(b"\n")
    )


def rendered(name, root=ROOT):
    source = (root / "stdlib/src/arithmetic" / f"{name}.vast").read_bytes()
    return HEADER + (IMPORTS if name == "generic" else b"") + public(source)


def package_sources(root=ROOT):
    """{path under stdlib/target/package/: the bytes that the script writes there}."""
    outputs = {
        "lib.vast": HEADER + b"pub mod arithmetic;\n" + b"".join(
            f"pub use {alias} as {name};\n".encode() for alias, name in LIBRARIES
        ),
        "arithmetic.vast": HEADER + b"".join(f"pub mod {module};\n".encode() for _, module in ARITHMETIC),
    }
    for source, module in ARITHMETIC:
        outputs[f"arithmetic/{module}.vast"] = rendered(source, root)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = package_sources()
    destination = ROOT / "stdlib/target/package"
    unexpected = sorted(
        path for path in destination.rglob("*.vast")
        if path.relative_to(destination).as_posix() not in outputs
    )
    if args.check and unexpected:
        raise SystemExit(f"{unexpected[0].relative_to(ROOT)} is unexpected; run python3 scripts/build_stdlib_package.py")
    for path in unexpected:
        path.unlink()
    for name, expected in outputs.items():
        path = destination / name
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"{path.relative_to(ROOT)} is missing or stale; run python3 scripts/build_stdlib_package.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_bytes() != expected:
                path.write_bytes(expected)


if __name__ == "__main__":
    main()
