#!/usr/bin/env python3
"""Generate the Rust table of indexed primitives from the kernel and fail on drift.

The kernel's `families` (lean-kernel/VastitasKernel/IndexedPrimitiveFamilies.lean)
list every indexed primitive's wire form: the `op`, whether only protocol 9 has
it, and the exact fields in wire order with their kinds. The frontend reads the
same list from `src/primitive_table.rs`, which this script renders from the
output of `scripts/primitive_table.lean`. By default the script compares the
rendering with the checked-in file and fails on any difference; `--write`
replaces the file. It builds the families module first, so the table never comes
from a stale `.olean`. `--families FILE` reads the JSON from a file instead of
running Lean.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
TABLE = Path("src/primitive_table.rs")
MODULE = "VastitasKernel.IndexedPrimitiveFamilies"
SCRIPT = "scripts/primitive_table.lean"
# The kernel's `Source.WireKind.wire` spellings and the Rust `WireKind` variants.
KINDS = {
    "path": "Path",
    "object_type": "ObjectType",
    "coordinate": "Coordinate",
    "polynomial": "Polynomial",
    "pullback_mode": "PullbackMode",
    "natural": "Natural",
}
NAME = re.compile(r"[a-z][a-z0-9_]*")
# rustfmt's defaults (there is no rustfmt.toml) lay out an array of two or more
# fields on one line when the fields take at most 60 columns, and one per line
# otherwise; a single field stays on its line. A field name of at most 34
# characters keeps every `(name, kind)` pair within rustfmt's 60-column call
# width, so no pair is split. scripts/test_check_primitive_table.py checks these layouts.
ARRAY_WIDTH = 60
MAX_FIELD_NAME = 34
HEADER = """\
//! The wire forms of the indexed primitives, generated by
//! `python3 scripts/check_primitive_table.py --write` from the kernel's
//! `families` (`lean-kernel/VastitasKernel/IndexedPrimitiveFamilies.lean`).
//! Do not edit: CI regenerates the table and fails on any difference.

use crate::indexed::{PrimitiveFamily, WireKind};

/// One family per wire `op`, in the kernel's order: whether only protocol 9
/// has it, and its fields in wire order.
pub(crate) const FAMILIES: &[PrimitiveFamily] = &[
"""


def kernel_families(root: Path) -> object:
    """Build the families module and return what the Lean script prints."""
    build = subprocess.run(["lake", "-d", "lean-kernel", "build", MODULE],
                           cwd=root, capture_output=True, text=True)
    if build.returncode != 0:
        raise RuntimeError(f"lake build {MODULE} failed:\n{build.stdout}{build.stderr}")
    run = subprocess.run(["lake", "-d", "lean-kernel", "env", "lean", SCRIPT],
                         cwd=root, capture_output=True, text=True)
    if run.returncode != 0:
        raise RuntimeError(f"{SCRIPT} failed:\n{run.stdout}{run.stderr}")
    try:
        return json.loads(run.stdout)
    except json.JSONDecodeError as error:
        raise RuntimeError(f"{SCRIPT} printed something other than one JSON value ({error}):\n{run.stdout}")


def validate(families: object) -> list[str]:
    """Why `families` is not a table the Rust frontend can hold, if it is not."""
    if not isinstance(families, list) or not families:
        return ["the families must be a non-empty JSON array"]
    errors, ops = [], set()
    for index, family in enumerate(families):
        where = f"family {index}"
        if not isinstance(family, dict) or set(family) != {"op", "algebraic", "fields"}:
            errors.append(f"{where}: expected exactly the keys op, algebraic and fields")
            continue
        op, algebraic, fields = family["op"], family["algebraic"], family["fields"]
        if not isinstance(op, str) or not NAME.fullmatch(op):
            errors.append(f"{where}: op {op!r} is not a lowercase identifier")
            continue
        where = f"family `{op}`"
        if op in ops:
            errors.append(f"{where}: duplicate op")
        ops.add(op)
        if not isinstance(algebraic, bool):
            errors.append(f"{where}: algebraic must be true or false")
        if not isinstance(fields, list):
            errors.append(f"{where}: fields must be an array")
            continue
        names = set()
        for field in fields:
            if not isinstance(field, dict) or set(field) != {"name", "kind"}:
                errors.append(f"{where}: each field has exactly the keys name and kind")
                continue
            name, kind = field["name"], field["kind"]
            if not isinstance(name, str) or not NAME.fullmatch(name) or name == "op":
                errors.append(f"{where}: field name {name!r} is not a lowercase identifier other than op")
            else:
                if len(name) > MAX_FIELD_NAME:
                    errors.append(f"{where}: field name `{name}` is longer than {MAX_FIELD_NAME} characters")
                elif name in names:
                    errors.append(f"{where}: duplicate field `{name}`")
                names.add(name)
            if not isinstance(kind, str) or kind not in KINDS:
                errors.append(f"{where}: unknown field kind {kind!r}")
    return errors


def render_fields(fields: list[dict]) -> list[str]:
    """The `fields:` line(s) of one family, as rustfmt lays them out."""
    items = [f'("{field["name"]}", WireKind::{KINDS[field["kind"]]})' for field in fields]
    if len(items) <= 1 or len(", ".join(items)) <= ARRAY_WIDTH:
        return [f"        fields: &[{', '.join(items)}],"]
    return ["        fields: &["] + [f"            {item}," for item in items] + ["        ],"]


def render(families: list[dict]) -> str:
    lines = []
    for family in families:
        lines += ["    PrimitiveFamily {",
                  f'        op: "{family["op"]}",',
                  f"        algebraic: {'true' if family['algebraic'] else 'false'},",
                  *render_fields(family["fields"]),
                  "    },"]
    return HEADER + "\n".join(lines) + "\n];\n"


def check(root: Path, families: object, write: bool) -> list[str]:
    errors = validate(families)
    if errors:
        return errors
    expected = render(families)
    path = root / TABLE
    if write:
        path.write_text(expected, encoding="utf-8")
        return []
    try:
        actual = path.read_text(encoding="utf-8")
    except OSError as error:
        return [f"{TABLE}: cannot read file: {error}"]
    if actual != expected:
        return [f"{TABLE} differs from the kernel's families; "
                "run `python3 scripts/check_primitive_table.py --write`"]
    return []


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"replace {TABLE} instead of comparing")
    parser.add_argument("--families", type=Path, help="read the families JSON from this file")
    arguments = parser.parse_args(argv)
    try:
        if arguments.families is not None:
            families = json.loads(arguments.families.read_text(encoding="utf-8"))
        else:
            families = kernel_families(root)
    except (OSError, ValueError, RuntimeError) as error:
        print(error, file=sys.stderr)
        return 1
    errors = check(root, families, arguments.write)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    verb = "wrote" if arguments.write else "matches"
    print(f"{TABLE}: {verb} the kernel's {len(families)} primitive families")
    return 0


if __name__ == "__main__":
    sys.exit(main())
