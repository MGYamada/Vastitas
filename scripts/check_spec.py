def paragraph(value):
    return " ".join(value.split())


def keys(value, where, required, optional, errors):
    if not isinstance(value, dict):
        errors.append(f"{where}: expected a table")
        return False
    for key in required:
        if key not in value:
            errors.append(f"{where}: missing `{key}`")
    for key in value:
        if key not in required and key not in optional:
            errors.append(f"{where}: unknown key `{key}`")
    return True


def text(value, key, where, errors):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, str) or not item.strip():
        errors.append(f"{where}: `{key}` must be a non-empty string")
        return None
    return paragraph(item)


def strings(value, key, where, errors, empty=False):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, list) or not all(isinstance(x, str) and x.strip() for x in item):
        errors.append(f"{where}: `{key}` must be a list of non-empty strings")
        return None
    if not item and not empty:
        errors.append(f"{where}: `{key}` must not be empty")
    repeated = sorted({x for x in item if item.count(x) > 1})
    if repeated:
        errors.append(f"{where}: `{key}` repeats {', '.join(repeated)}")
    return [paragraph(x) for x in item]


def load_toml(root, path, errors):
    try:
        with open(root / path, "rb") as file:
            return tomllib.load(file)
    except OSError as error:
        errors.append(f"{path}: cannot read: {error}")
    except tomllib.TOMLDecodeError as error:
        errors.append(f"{path}: invalid TOML: {error}")
    return None


def parse_claim(name, table, where, errors):
    if not SHORT_ID.fullmatch(name):
        errors.append(f"{where}: invalid claim name (use lower-case words joined by hyphens)")
    if not isinstance(table, dict):
        errors.append(f"{where}: expected a table")
        return None
    status = table.get("status")
    if status not in STATUSES:
        errors.append(f"{where}: unknown status {status!r}; use one of {', '.join(STATUSES)}")
        return None
    required, optional = CLAIM_KEYS[status]
    keys(table, where, ("status", *required), optional, errors)
    claim = Claim(name, status)
    claim.evidence = strings(table, "evidence", where, errors) or []
    claim.premises = strings(table, "premises", where, errors, empty=True)
    if status in PROVED and claim.premises is None and "premises" in table:
        claim.premises = []
    claim.assumes = strings(table, "assumes", where, errors) or []
    claim.reason = text(table, "reason", where, errors)
    claim.note = text(table, "note", where, errors)
    issue = table.get("issue")
    if issue is not None:
        if isinstance(issue, bool) or not isinstance(issue, int) or issue <= 0:
            errors.append(f"{where}: `issue` must be a positive issue number")
        else:
            claim.issue = issue
    enforced = table.get("enforced_by")
    if enforced is not None:
        if not isinstance(enforced, list) or not enforced:
            errors.append(f"{where}: `enforced_by` must be a non-empty list of tables")
        else:
            for index, item in enumerate(enforced):
                at = f"{where} enforced_by[{index}]"
                if not keys(item, at, ("definition", "code"), (), errors):
                    continue
                definition, code = item.get("definition"), item.get("code")
                if not isinstance(definition, str) or not LEAN_NAME.fullmatch(definition) \
                        or not definition.startswith("VastitasKernel."):
                    errors.append(f"{at}: `definition` must be a fully qualified kernel definition "
                                  "under VastitasKernel")
                    definition = None
                if not isinstance(code, str) or not DIAGNOSTIC.fullmatch(code):
                    errors.append(f"{at}: `code` must be a diagnostic code such as E_METRIC")
                    code = None
                claim.enforced_by.append((definition, code))
    return claim


def parse_rule(value, where, root, errors):
    if value is None:
        return ("", "")
    match = LINK.fullmatch(value.strip()) if isinstance(value, str) else None
    if not match or ".." in match.group(2):
        errors.append(f"{where}: `specified_in` must be one Markdown link to a book chapter, "
                      "such as [Laws](adr/0001-mathematics-first-stdlib.md#laws)")
        return ("", "")
    label, target, anchor = match.group(1), match.group(2), match.group(3) or ""
    if not (root / "docs" / target).is_file():
        errors.append(f"{where}: `specified_in` names docs/{target}, which does not exist")
    return (paragraph(label), target + anchor)


def parse_property(identifier, table, prefix, where, root, errors):
    if not PROPERTY_ID.fullmatch(identifier):
        errors.append(f"{where}: invalid property id (use dot-separated lower-case words)")
    elif prefix and not identifier.startswith(prefix + "."):
        errors.append(f"{where}: the property id must begin with `{prefix}.`, the file's `id`")
    if not keys(table, where, *PROPERTY_KEYS, errors):
        return None
    values = {key: text(table, key, where, errors) for key in
              ("title", "subject", "statement", "example", "example_test", "example_not_executed")}
    if values["title"] and "|" in values["title"]:
        errors.append(f"{where}: `title` must not contain `|`")
    if ("example_test" in table) == ("example_not_executed" in table):
        errors.append(f"{where}: give exactly one of `example_test` (the test that runs the example) "
                      "and `example_not_executed` (why no test runs it)")
    rule = parse_rule(table.get("specified_in"), where, root, errors)
    claims = []
    tables = table.get("claim")
    if tables is not None:
        if not isinstance(tables, dict) or not tables:
            errors.append(f"{where}: needs at least one `claim` table")
        else:
            for name, claim_table in tables.items():
                claim = parse_claim(name, claim_table, f'{where} claim.{name}', errors)
                if claim:
                    claims.append(claim)
    return Property(identifier, values["title"] or identifier, values["subject"] or "",
                    values["statement"] or "", rule, values["example"] or "",
                    values["example_test"], values["example_not_executed"], claims)


def parse_spec(root, path, errors):
    data = load_toml(root, path, errors)
    if data is None:
        return None
    for key in data:
        if key == "symbol":
            errors.append(f"{path}: `symbol` records are reserved for the std admission manifest "
                          "(#285), which has not defined their fields")
        elif key not in ("spec", "property"):
            errors.append(f"{path}: unknown table `{key}`")
    header = data.get("spec")
    if header is None:
        errors.append(f"{path}: missing the `[spec]` table")
        return None
    if not keys(header, f"{path} [spec]", ("id", "title", "subject", "description"), (), errors):
        return None
    values = {key: text(header, key, f"{path} [spec]", errors)
              for key in ("id", "title", "subject", "description")}
    if values["id"] and not FILE_ID.fullmatch(values["id"]):
        errors.append(f"{path} [spec]: invalid `id` (use lower-case words joined by hyphens)")
    if values["title"] and ("|" in values["title"] or "]" in values["title"]):
        errors.append(f"{path} [spec]: `title` must not contain `|` or `]`")
    properties = []
    tables = data.get("property")
    if not isinstance(tables, dict) or not tables:
        errors.append(f"{path}: defines no property")
    else:
        for identifier, table in tables.items():
            item = parse_property(identifier, table, values["id"], f'{path} [property."{identifier}"]',
                                  root, errors)
            if item:
                properties.append(item)
    return Spec(path, values["id"] or path.stem, values["title"] or path.stem,
                values["subject"] or "", values["description"] or "", properties)


def parse_registry(root, errors):
    if not (root / REGISTRY).exists():
        return {}
    data = load_toml(root, REGISTRY, errors)
    if data is None:
        return {}
    for key in data:
        if key != "assumption":
            errors.append(f"{REGISTRY}: unknown table `{key}`")
    registry = {}
    entries = data.get("assumption", {})
    if not isinstance(entries, dict):
        errors.append(f"{REGISTRY}: `assumption` must be a table of assumptions")
        entries = {}
    for identifier, table in entries.items():
        where = f"{REGISTRY} [assumption.{identifier}]"
        if not SHORT_ID.fullmatch(identifier):
            errors.append(f"{where}: invalid assumption id (use lower-case words joined by hyphens)")
        if not keys(table, where, ("title", "statement"), (), errors):
            continue
        title, statement = text(table, "title", where, errors), text(table, "statement", where, errors)
        if title and "|" in title:
            errors.append(f"{where}: `title` must not contain `|`")
        registry[identifier] = Assumption(identifier, title or identifier, statement or "")
    return registry


# Tests and the CI steps that run them.

ATTRIBUTE = re.compile(r"#\s*\[\s*([A-Za-z_][A-Za-z0-9_]*)")
FUNCTION = re.compile(r"(?:pub(?:\s*\([^)]*\))?\s+)?(?:const\s+)?(?:async\s+)?(?:unsafe\s+)?"
                      r"fn\s+([A-Za-z_][A-Za-z0-9_]*)")


def rust_tests(source):
    """`#[test]` functions of a Rust source, mapped to whether they are `#[ignore]`d."""
    tests, attributes = {}, []
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith("#["):
            match = ATTRIBUTE.match(stripped)
            if match:
                attributes.append(match.group(1))
            continue
        if not stripped or stripped.startswith("//"):
            continue
        match = FUNCTION.match(stripped)
        if match and "test" in attributes:
            tests[match.group(1)] = "ignore" in attributes
        attributes = []
    return tests


def python_tests(source):
    """(class, method) of the test methods of a unittest module, mapped to an unconditional skip."""
    tests = {}

    def skipped(node):
        for decorator in node.decorator_list:
            target = decorator.func if isinstance(decorator, ast.Call) else decorator
            name = target.attr if isinstance(target, ast.Attribute) else getattr(target, "id", "")
            if name == "skip":
                return True
        return False

    for node in ast.parse(source).body:
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name.startswith("test"):
                    tests[(node.name, item.name)] = skipped(node) or skipped(item)
    return tests


def pull_request_trigger(workflow):
    lines = workflow.splitlines()
    for index, line in enumerate(lines):
        match = re.match(r"""^(?:on|"on"|'on'):\s*([^#]*)""", line)
        if not match:
            continue
        inline = match.group(1).strip()
        if inline:
            return "pull_request" in re.findall(r"[A-Za-z_]+", inline)
        for nested in lines[index + 1:]:
            if nested.strip() and not nested[0].isspace() and not nested.startswith("#"):
                break
            if re.match(r"^\s+(?:-\s*)?pull_request\s*(?::|$)", nested):
                return True
        return False
    return False


RUN = re.compile(r"^(\s*)(-\s+)?run:\s*(.*?)\s*$")


def run_scripts(workflow):
    """The text of every `run:` step of a workflow."""
    lines = workflow.splitlines()
    scripts, index = [], 0
    while index < len(lines):
        match = RUN.match(lines[index])
        index += 1
        if not match:
            continue
        indent = len(match.group(1)) + len(match.group(2) or "")
        value = match.group(3)
        if value[:1] in ("|", ">"):
            body = []
            while index < len(lines) and (not lines[index].strip()
                                          or len(lines[index]) - len(lines[index].lstrip()) > indent):
                body.append(lines[index])
                index += 1
            scripts.append(textwrap.dedent("\n".join(body)))
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            scripts.append(value[1:-1])
        else:
            scripts.append(re.sub(r"\s+#.*$", "", value))
    return scripts


def commands(script):
    """Simple commands of a shell script: continuations joined, split at `;`, `&&`, `||` and `|`."""
    for line in script.replace("\\\n", " ").splitlines():
        for part in re.split(r"&&|\|\||;|\|", line):
            try:
                tokens = shlex.split(part, comments=True)
            except ValueError:
                continue
            while tokens and tokens[0] in ("then", "else", "do", "if", "!", "time"):
                tokens = tokens[1:]
            while tokens and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*=.*", tokens[0]):
                tokens = tokens[1:]
            if tokens:
                yield tokens


CARGO_VALUES = {"--bin", "--example", "--bench", "-p", "--package", "--features", "-F", "--manifest-path",
                "--target", "--target-dir", "-j", "--jobs", "--profile", "--color", "--message-format",
                "--exclude", "-Z", "--config"}
CARGO_TARGETS = {"--lib", "--bins", "--bin", "--examples", "--example", "--benches", "--bench", "--doc"}
LIBTEST_VALUES = {"--skip", "--test-threads", "--format", "--color", "-Z", "--logfile", "--shuffle-seed"}


@dataclass
class CargoRun:
    every_test: bool
    targets: set
    ignored: str
    filters: list
    skips: list
    exact: bool

    def runs(self, stem, name, ignored):
        if not (self.every_test or stem in self.targets):
            return False
        if ignored and self.ignored == "exclude" or not ignored and self.ignored == "only":
            return False
        def matches(pattern):
            return name == pattern if self.exact else pattern in name
        if any(matches(skip) for skip in self.skips):
            return False
        return not self.filters or any(matches(item) for item in self.filters)


def cargo_run(arguments):
    split = arguments.index("--") if "--" in arguments else len(arguments)
    before, after = arguments[:split], arguments[split + 1:]
    run = CargoRun(False, set(), "exclude", [], [], False)
    selected, items = False, iter(before)
    for argument in items:
        name, _, attached = argument.partition("=") if argument.startswith("--") else (argument, "", "")
        if name in ("--all-targets", "--tests"):
            run.every_test = selected = True
        elif name == "--test":
            selected = True
            run.targets.add(attached or next(items, ""))
        elif name in CARGO_TARGETS:
            selected = True
            if name in CARGO_VALUES and not attached:
                next(items, None)
        elif name in CARGO_VALUES and not attached:
            next(items, None)
        elif not argument.startswith("-"):
            run.filters.append(argument)
    if not selected:
        run.every_test = True
    items = iter(after)
    for argument in items:
        if argument == "--ignored":
            run.ignored = "only"
        elif argument == "--include-ignored":
            run.ignored = "include"
        elif argument == "--exact":
            run.exact = True
        elif argument == "--skip":
            run.skips.append(next(items, ""))
        elif argument in LIBTEST_VALUES:
            next(items, None)
        elif not argument.startswith("-"):
            run.filters.append(argument)
    return run


@dataclass
class DiscoverRun:
    start: PurePosixPath
    pattern: str
    selections: list

    def runs(self, path, test_class, method):
        path = PurePosixPath(path)
        if path.parent != self.start or not fnmatch.fnmatchcase(path.name, self.pattern):
            return False
        full = f"{path.stem}.{test_class}.{method}"
        return not self.selections or any(
            fnmatch.fnmatchcase(full, item) if "*" in item else item in full for item in self.selections)


def discover_run(arguments):
    start, pattern, positional, selections = ".", "test*.py", [], []
    items = iter(arguments)
    for argument in items:
        if argument in ("-s", "--start-directory"):
            start = next(items, start)
        elif argument in ("-p", "--pattern"):
            pattern = next(items, pattern)
        elif argument in ("-t", "--top-level-directory"):
            next(items, None)
        elif argument == "-k":
            selections.append(next(items, ""))
        elif not argument.startswith("-"):
            positional.append(argument)
    if positional:
        start = positional[0]
    if len(positional) > 1:
        pattern = positional[1]
    return DiscoverRun(PurePosixPath(os.path.normpath(start)), pattern, selections)


class Repository:
    """The tests, the CI steps, the kernel regressions and the diagnostic codes of a checkout."""

    def __init__(self, root):
        self.root = root
        self.cargo, self.discover, self.regression_steps = [], [], 0
        directory = root / WORKFLOWS
        workflows = sorted(directory.glob("*.yml")) + sorted(directory.glob("*.yaml")) if directory.is_dir() else []
        for path in workflows:
            workflow = path.read_text(encoding="utf-8")
            if not pull_request_trigger(workflow):
                continue
            for script in run_scripts(workflow):
                for tokens in commands(script):
                    self.add(tokens)
        self.regressions = set()
        if (root / REGRESSIONS).is_file():
            for tokens in commands((root / REGRESSIONS).read_text(encoding="utf-8")):
                if tokens[:4] == ["lake", "-d", "lean-kernel", "build"]:
                    self.regressions.update(item for item in tokens[4:] if LEAN_NAME.fullmatch(item))
        self.codes = set()
        if (root / DIAGNOSTICS).is_file():
            self.codes = set(re.findall(r"`(E_[A-Z0-9_]+)`", (root / DIAGNOSTICS).read_text(encoding="utf-8")))
        self._rust, self._python = {}, {}

    def add(self, tokens):
        for index in range(len(tokens) - 1):
            if os.path.basename(tokens[index]) == "cargo" and tokens[index + 1] == "test":
                self.cargo.append(cargo_run(tokens[index + 2:]))
            if tokens[index] == "-m" and tokens[index + 1:index + 3] == ["unittest", "discover"]:
                self.discover.append(discover_run(tokens[index + 3:]))
        if any(item.endswith(str(REGRESSIONS)) for item in tokens):
            self.regression_steps += 1

    def rust(self, path):
        if path not in self._rust:
            file = self.root / path
            self._rust[path] = rust_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
        return self._rust[path]

    def python(self, path):
        if path not in self._python:
            file = self.root / path
            try:
                self._python[path] = python_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
            except SyntaxError:
                self._python[path] = None
        return self._python[path]

    def check_test(self, item, where, errors):
        """Check one Tested reference: the test exists and a CI step runs it."""
        if match := RUST_TEST.fullmatch(item):
            path, name = match.groups()
            tests = self.rust(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist")
            elif name not in tests:
                errors.append(f"{where}: {path} has no #[test] function `{name}`")
            elif not any(run.runs(PurePosixPath(path).stem, name, tests[name]) for run in self.cargo):
                if tests[name]:
                    errors.append(f"{where}: `{item}` is #[ignore]d, and no CI step passes --ignored for it")
                else:
                    errors.append(f"{where}: no CI step runs `{item}`")
        elif match := PYTHON_TEST.fullmatch(item):
            path, test_class, method = match.groups()
            tests = self.python(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist or does not parse")
            elif (test_class, method) not in tests:
                errors.append(f"{where}: {path} has no test method `{test_class}.{method}`")
            elif tests[(test_class, method)]:
                errors.append(f"{where}: `{item}` is skipped unconditionally")
            elif not any(run.runs(path, test_class, method) for run in self.discover):
                errors.append(f"{where}: no CI step runs `{item}`")
        elif LEAN_NAME.fullmatch(item):
            if item not in self.regressions:
                errors.append(f"{where}: `{item}` is not a module that {REGRESSIONS} builds")
            elif not module_source(self.root, item):
                errors.append(f"{where}: the regression module `{item}` has no source file")
            elif not self.regression_steps:
                errors.append(f"{where}: no CI step runs {REGRESSIONS}")
        else:
            errors.append(f"{where}: `{item}` is not a test reference: use tests/<file>.rs::<function>, "
                          "<directory>/test_<name>.py::<Class>::<method> or a kernel regression module")

    def tested_form(self, item):
        return bool(RUST_TEST.fullmatch(item) or PYTHON_TEST.fullmatch(item) or item in self.regressions)


def module_path(module):
    top = module.split(".", 1)[0]
    if top not in SOURCES:
        return None
    return PurePosixPath(SOURCES[top], *module.split(".")).with_suffix(".lean")


def module_source(root, module):
    path = module_path(module)
    return path is not None and (root / path).is_file()


# Statement pins.

def load_pins(root, environment, errors):
    path = PINS / f"{environment}.json"
    if not (root / path).exists():
        return {}
    try:
        data = json.loads((root / path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        errors.append(f"{path}: cannot read: {error}")
        return {}
    rules = ENVIRONMENTS[environment]
    if not isinstance(data, dict) or set(data) != {"format", "environment", "imports", "entries"} \
            or data.get("format") != 1 or data.get("environment") != environment \
            or not isinstance(data.get("imports"), list) or not isinstance(data.get("entries"), list):
        errors.append(f"{path}: expected format 1 with `environment` {environment!r}, `imports` and `entries`")
        return {}
    pins, names, modules = {}, [], set()
    for index, entry in enumerate(data["entries"]):
        where = f"{path} entries[{index}]"
        kind = entry.get("kind") if isinstance(entry, dict) else None
        expected = {"name", "module", "kind", "statement"} if kind == "theorem" else {"name", "module", "kind"}
        if not isinstance(entry, dict) or kind not in ("theorem", "definition") or set(entry) != expected \
                or not all(isinstance(entry[key], str) for key in expected):
            errors.append(f"{where}: expected a theorem with `name`, `module`, `kind` and `statement`, "
                          "or a definition with `name`, `module` and `kind`")
            continue
        name, module = entry["name"], entry["module"]
        root_name = rules["theorems"] if kind == "theorem" else rules["definitions"]
        if root_name is None:
            errors.append(f"{where}: the {environment} environment resolves no kernel definitions")
            continue
        if not LEAN_NAME.fullmatch(name) or not name.startswith(root_name + "."):
            errors.append(f"{where}: `{name}` is not a fully qualified name under {root_name}")
        if not LEAN_NAME.fullmatch(module) or not module.startswith(root_name + "."):
            errors.append(f"{where}: the module `{module}` of `{name}` is not under {root_name}")
        elif not module_source(root, module):
            errors.append(f"{where}: the module `{module}` of `{name}` has no source file {module_path(module)}")
        if kind == "theorem" and not STATEMENT.fullmatch(entry["statement"]):
            errors.append(f"{where}: `statement` must be sha256: followed by 64 lower-case hex digits")
        if name in pins:
            errors.append(f"{where}: `{name}` is pinned twice")
        pins[name], modules = entry, modules | {module}
        names.append(name)
    if names != sorted(names):
        errors.append(f"{path}: entries must be sorted by name")
    if data["imports"] != sorted(modules):
        errors.append(f"{path}: `imports` must list exactly the pinned modules, sorted")
    return pins


def format_pins(environment, entries):
    lines = ["{", '  "format": 1,', f'  "environment": {json.dumps(environment)},']
    modules = sorted({entry["module"] for entry in entries})
    lines.append('  "imports": [' + ("" if modules else "],"))
    lines += [f"    {json.dumps(m)}{',' if i + 1 < len(modules) else ''}" for i, m in enumerate(modules)]
    if modules:
        lines.append("  ],")
    lines.append('  "entries": [' + ("" if entries else "]"))
    for index, entry in enumerate(entries):
        keys_in_order = ["name", "module", "kind"] + (["statement"] if entry["kind"] == "theorem" else [])
        body = ", ".join(f"{json.dumps(key)}: {json.dumps(entry[key], ensure_ascii=False)}"
                         for key in keys_in_order)
        lines.append(f"    {{{body}}}{',' if index + 1 < len(entries) else ''}")
    if entries:
        lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


# Loading and checking.

def load(root, errors):
    repository = Repository(root)
    registry = parse_registry(root, errors)
    specs, owners = [], {}
    directory = root / SPEC
    files = sorted(directory.glob("*.toml")) if directory.is_dir() else []
    for file in files:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path == REGISTRY:
            continue
        spec = parse_spec(root, path, errors)
        if spec:
            specs.append(spec)
    file_ids = {}
    for spec in specs:
        if spec.id in file_ids:
            errors.append(f"{spec.path}: the file id `{spec.id}` is also used by {file_ids[spec.id]}")
        file_ids[spec.id] = spec.path
        for item in spec.properties:
            if item.id in owners:
                errors.append(f'{spec.path} [property."{item.id}"]: duplicate property id; '
                              f"{owners[item.id]} defines it too")
            owners[item.id] = spec.path
    cited = {environment: {} for environment in ENVIRONMENTS}
    for spec in specs:
        for item in spec.properties:
            where = f'{spec.path} [property."{item.id}"]'
            if item.example_test:
                repository.check_test(item.example_test, f"{where} example_test", errors)
            for claim in item.claims:
                check_claim(claim, f"{where} claim.{claim.name}", repository, registry, cited, errors)
    pins = {environment: load_pins(root, environment, errors) for environment in ENVIRONMENTS}
    for environment, names in cited.items():
        path = PINS / f"{environment}.json"
        update = f"run `python3 scripts/check_spec.py --update-statements {environment}`"
        for name, kinds in sorted(names.items()):
            pin = pins[environment].get(name)
            if len(kinds) > 1:
                errors.append(f"`{name}` is cited both as a theorem and as a kernel definition")
            elif pin is None:
                errors.append(f"{path}: `{name}` is cited but not pinned; {update}")
            elif pin["kind"] not in kinds:
                errors.append(f"{path}: `{name}` is cited as a {next(iter(kinds))} but pinned as a {pin['kind']}")
        for name in sorted(pins[environment].keys() - names.keys()):
            errors.append(f"{path}: `{name}` is pinned but no claim cites it; {update}")
    outputs = {spec.chapter: render_spec(spec, pins, registry) for spec in specs}
    if registry or (root / REGISTRY).exists():
        outputs[REGISTRY.with_suffix(".md")] = render_registry(registry, specs)
    return State(specs, registry, pins, cited, outputs)


def check_claim(claim, where, repository, registry, cited, errors):
    if claim.status in PROVED:
        environment = PROVED[claim.status]
        root_name = ENVIRONMENTS[environment]["theorems"]
        for item in claim.evidence:
            if repository.tested_form(item):
                errors.append(f"{where}: `{item}` is Tested evidence; a {STATUSES[claim.status]} claim "
                              f"cites theorems under {root_name}")
            elif not LEAN_NAME.fullmatch(item) or not item.startswith(root_name + "."):
                errors.append(f"{where}: `{item}` is not a fully qualified theorem name under {root_name}")
            else:
                cited[environment].setdefault(item, set()).add("theorem")
    elif claim.status == "tested":
        for item in claim.evidence:
            repository.check_test(item, where, errors)
    elif claim.status == "assumed":
        for item in claim.evidence:
            if item not in registry:
                errors.append(f"{where}: unknown assumption `{item}`; {REGISTRY} lists the assumptions")
    for item in claim.assumes:
        if item not in registry:
            errors.append(f"{where}: unknown assumption `{item}` in `assumes`; {REGISTRY} lists the assumptions")
    for definition, code in claim.enforced_by:
        if definition:
            cited["oracle"].setdefault(definition, set()).add("definition")
        if code and code not in repository.codes:
            errors.append(f"{where}: unknown diagnostic code `{code}`; {DIAGNOSTICS} lists every code")


def check(root):
    errors = []
    state = load(root, errors)
    for path, expected in state.outputs.items():
        file = root / path
        if not file.is_file() or file.read_text(encoding="utf-8") != expected:
            errors.append(f"{path}: out of date; run `python3 scripts/check_spec.py --write`")
    directory = root / SPEC
    for file in sorted(directory.glob("*.md")) if directory.is_dir() else []:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path not in state.outputs:
            errors.append(f"{path}: no spec file generates this chapter")
    summary = (root / SUMMARY).read_text(encoding="utf-8") if (root / SUMMARY).is_file() else ""
    for path in state.outputs:
        link = path.relative_to("docs").as_posix()
        if f"]({link})" not in summary:
            errors.append(f"{SUMMARY}: does not list the generated chapter {link}")
    return errors, state


def write(root, state):
    for path, contents in state.outputs.items():
        (root / path).write_text(contents, encoding="utf-8")
    directory = root / SPEC
    for file in sorted(directory.glob("*.md")) if directory.is_dir() else []:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path not in state.outputs and MARKER in file.read_text(encoding="utf-8"):
            file.unlink()


# Chapters.

def link_module(module):
    path = module_path(module)
    return f"[`{module}`]({BLOB}{path})" if path else f"`{module}`"


def assumption_link(identifier, registry):
    entry = registry.get(identifier)
    title = entry.title if entry else identifier
    return f"[{title}](assumptions.md#assumption.{identifier})"


def test_reference(item):
    if match := RUST_TEST.fullmatch(item):
        return f"`{match.group(2)}` in [`{match.group(1)}`]({BLOB}{match.group(1)})"
    if match := PYTHON_TEST.fullmatch(item):
        return f"`{match.group(2)}.{match.group(3)}` in [`{match.group(1)}`]({BLOB}{match.group(1)})"
    return f"{link_module(item)}, built by [`{REGRESSIONS}`]({BLOB}{REGRESSIONS})"


def lean_evidence(names, pins):
    groups = {}
    for name in names:
        pin = pins.get(name)
        groups.setdefault(pin["module"] if pin else None, []).append(name)
    lines = []
    for module, members in groups.items():
        listed = ", ".join(f"`{name}`" for name in members)
        lines.append(f"{link_module(module)}: {listed}" if module else f"not pinned: {listed}")
    return lines


def claim_lines(claim, pins, registry):
    lines = [f"- `{claim.name}`: [{STATUSES[claim.status]}](../specifications.md#{claim.status})"]
    if claim.status in PROVED:
        lines.append("  - Evidence:")
        lines += [f"    - {line}" for line in lean_evidence(claim.evidence, pins[PROVED[claim.status]])]
    elif claim.status == "tested":
        lines.append("  - Evidence:")
        lines += [f"    - {test_reference(item)}" for item in claim.evidence]
    elif claim.status == "assumed":
        lines.append("  - Evidence: " + ", ".join(assumption_link(item, registry) for item in claim.evidence))
    if claim.premises is not None:
        if claim.premises:
            lines.append("  - Premises:")
            lines += [f"    - {premise}" for premise in claim.premises]
        else:
            lines.append("  - Premises: none")
    if claim.assumes:
        lines.append("  - Assumes: " + ", ".join(assumption_link(item, registry) for item in claim.assumes))
    for definition, code in claim.enforced_by:
        pin = pins["oracle"].get(definition) if definition else None
        where = f" in {link_module(pin['module'])}" if pin else ""
        lines.append(f"  - Enforced by: `{definition}`{where}, which reports `{code}`")
    if claim.reason:
        lines.append(f"  - Reason: {claim.reason}")
    if claim.issue:
        lines.append(f"  - Issue: [#{claim.issue}]({ISSUES}{claim.issue})")
    if claim.note:
        lines.append(f"  - Note: {claim.note}")
    return lines


def render_spec(spec, pins, registry):
    lines = [f"# {spec.title}", "",
             f"{MARKER} from {spec.path}. Edit that file and run `python3 scripts/check_spec.py --write`. -->",
             "", spec.description, "",
             f"[Specifications](../specifications.md) defines the "
             f"[claim statuses](../specifications.md#claim-statuses) and the checks. This chapter is "
             f"generated from [`{spec.path}`]({BLOB}{spec.path}).", "",
             "| Property | Claims |", "| --- | --- |"]
    for item in spec.properties:
        lines.append(f"| [{item.title}](#{item.id}) | "
                     f"{', '.join(STATUSES[claim.status] for claim in item.claims)} |")
    for item in spec.properties:
        label, target = item.rule
        lines += ["", f'<a id="{item.id}"></a>', "", f"## {item.title}", "",
                  f"- Property: `{item.id}`", f"- Subject: `{item.subject}`",
                  f"- Rule: [{label}](../{target})", "", item.statement, "",
                  f"- Example: {item.example}"]
        if item.example_test:
            lines.append(f"- Run by: {test_reference(item.example_test)}")
        else:
            lines.append(f"- Not executed: {item.example_not_executed}")
        lines += ["", "Claims:", ""]
        for claim in item.claims:
            lines += claim_lines(claim, pins, registry)
    return "\n".join(lines) + "\n"


def render_registry(registry, specs):
    citations = {identifier: [] for identifier in registry}
    for spec in specs:
        for item in spec.properties:
            for claim in item.claims:
                used = (claim.evidence if claim.status == "assumed" else []) + claim.assumes
                for identifier in dict.fromkeys(used):
                    if identifier in citations:
                        citations[identifier].append(
                            f"[`{item.id}`]({spec.chapter.name}#{item.id}) (`{claim.name}`)")
    lines = ["# Assumptions", "",
             f"{MARKER} from {REGISTRY}. Edit that file and run `python3 scripts/check_spec.py --write`. -->",
             "", "The assumption registry lists the trusted components that claims rest on. A claim with "
             "status [Assumed](../specifications.md#assumed) cites an entry as its evidence. A Proved or "
             "Tested claim names in `assumes` the entries that its evidence does not discharge. This chapter "
             f"is generated from [`{REGISTRY}`]({BLOB}{REGISTRY}).", "",
             "| Assumption | Claims that cite it |", "| --- | --- |"]
    for identifier, entry in registry.items():
        lines.append(f"| [{entry.title}](#assumption.{identifier}) | {len(citations[identifier])} |")
    for identifier, entry in registry.items():
        lines += ["", f'<a id="assumption.{identifier}"></a>', "", f"## {entry.title}", "",
                  f"- Assumption: `{identifier}`", "", entry.statement, ""]
        if citations[identifier]:
            lines.append("Cited by:")
            lines.append("")
            lines += [f"- {citation}" for citation in citations[identifier]]
        else:
            lines.append("No claim cites this assumption.")
    return "\n".join(lines) + "\n"


# Statement pins from the Lean resolver.

def update_statements(root, environment):
    errors = []
    state = load(root, errors)
    names = state.cited[environment]
    blocking = [error for error in errors if PINS.as_posix() not in error and "out of date" not in error]
    if blocking:
        print("\n".join(blocking), file=sys.stderr)
        print("fix these errors before updating the statement pins", file=sys.stderr)
        return 1
    rules = ENVIRONMENTS[environment]
    request = {"format": 1, "environment": environment, "imports": rules["discover"],
               "entries": [{"name": name, "kind": next(iter(kinds))} for name, kinds in sorted(names.items())]}
    with tempfile.TemporaryDirectory(prefix="vastitas-spec-") as directory:
        source, report = Path(directory) / "request.json", Path(directory) / "report.json"
        source.write_text(json.dumps(request), encoding="utf-8")
        result = subprocess.run(
            ["lake", "env", "lean", str(root / RESOLVER)], cwd=root / rules["directory"], text=True,
            env=dict(os.environ, VASTITAS_SPEC_INPUT=str(source), VASTITAS_SPEC_REPORT=str(report)),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, check=False)
        if result.returncode or not report.is_file():
            print(result.stdout, file=sys.stderr)
            print(f"the resolver failed in {rules['directory']}/; build that package first", file=sys.stderr)
            return 1
        facts = json.loads(report.read_text(encoding="utf-8"))
    if facts.get("problems"):
        print("\n".join(facts["problems"]), file=sys.stderr)
        return 1
    entries = sorted(({key: entry[key] for key in ("name", "module", "kind", "statement") if key in entry}
                      for entry in facts["entries"]), key=lambda entry: entry["name"])
    old = state.pins[environment]
    for entry in entries:
        before = old.get(entry["name"])
        if before is None:
            print(f"pinned {entry['name']}")
        elif before != entry:
            print(f"changed {entry['name']}: review its statement and module")
    for name in sorted(old.keys() - {entry["name"] for entry in entries}):
        print(f"removed {name}")
    path = root / PINS / f"{environment}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_pins(environment, entries), encoding="utf-8")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the chapters under docs/spec/")
    group.add_argument("--update-statements", choices=sorted(ENVIRONMENTS), metavar="ENVIRONMENT",
                       help="rewrite docs/spec/pins/ENVIRONMENT.json from the built Lean package")
    arguments = parser.parse_args(argv)
    if arguments.update_statements and update_statements(ROOT, arguments.update_statements):
        return 1
    if arguments.write or arguments.update_statements:
        write(ROOT, load(ROOT, []))
    errors, state = check(ROOT)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    properties = sum(len(spec.properties) for spec in state.specs)
    claims = sum(len(item.claims) for spec in state.specs for item in spec.properties)
    pinned = ", ".join(f"{len(state.pins[environment])} {environment}" for environment in ENVIRONMENTS)
    print(f"Specifications: {len(state.specs)} files, {properties} properties and {claims} claims; "
          f"statement pins: {pinned}; every generated chapter is fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
