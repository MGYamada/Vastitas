"""Check the specification files under docs/spec/ and generate their chapters.

A property states a fact about a language construct or a standard-library
module. Each claim about a property has one status, and its evidence must
resolve. This script checks every rule that needs no Lean: the file format,
the status of each claim and the form of its evidence, the tests and the CI
steps that run them, the assumption registry, the diagnostic codes, the name
sets of the statement pins and the freshness of the generated chapters.
scripts/spec_resolve.lean checks the pinned Lean declarations themselves.
docs/specifications.md describes both checks.

    python3 scripts/check_spec.py                              check
    python3 scripts/check_spec.py --write                      regenerate the chapters
    python3 scripts/check_spec.py --update-statements oracle   rewrite docs/spec/pins/oracle.json

--update-statements needs the built Lean package of that environment: it runs
the resolver in report mode, from lean/ or from lean-bridge/.
"""
