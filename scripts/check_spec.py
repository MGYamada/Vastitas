def paragraph(value):
    return " ".join(value.split())


def inline(value):
    """Escape HTML outside code spans, so that text such as Pair<Int> renders as written."""
    parts = value.split("`")
    for index in range(0, len(parts), 2):
        parts[index] = parts[index].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return "`".join(parts)


def keys(value, where, required, optional, errors):
    if not isinstance(value, dict):
        errors.append(f"{where}: expected a table")
        return False
    for key in required:
        if key not in value:
            errors.append(f"{where}: missing `{key}`")
    for key in value:
        if key not in required and key not in optional:
            errors.append(f"{where}: unknown key `{key}`")
    return True


def text(value, key, where, errors):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, str) or not item.strip():
        errors.append(f"{where}: `{key}` must be a non-empty string")
        return None
    if item.count("`") % 2:
        errors.append(f"{where}: `{key}` has an unmatched backquote")
    return paragraph(item)


def strings(value, key, where, errors, empty=False):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, list) or not all(isinstance(x, str) and x.strip() for x in item):
        errors.append(f"{where}: `{key}` must be a list of non-empty strings")
        return None
    if not item and not empty:
        errors.append(f"{where}: `{key}` must not be empty")
    if any(x.count("`") % 2 for x in item):
        errors.append(f"{where}: an item of `{key}` has an unmatched backquote")
    repeated = sorted({x for x in item if item.count(x) > 1})
    if repeated:
        errors.append(f"{where}: `{key}` repeats {', '.join(repeated)}")
    return [paragraph(x) for x in item]


def title_rule(title, where, errors):
    """Titles appear in headings, tables and link text, so they hold no markup."""
    if title and any(c in title for c in "|[]<>`"):
        errors.append(f"{where}: `title` must not contain `|`, `[`, `]`, `<`, `>` or a backquote")


def load_toml(root, path, errors):
    try:
        with open(root / path, "rb") as file:
            return tomllib.load(file)
    except OSError as error:
        errors.append(f"{path}: cannot read: {error}")
    except tomllib.TOMLDecodeError as error:
        errors.append(f"{path}: invalid TOML: {error}")
    return None


def parse_claim(name, table, where, errors):
    if not SHORT_ID.fullmatch(name):
        errors.append(f"{where}: invalid claim name (use lower-case words joined by hyphens)")
    if not isinstance(table, dict):
        errors.append(f"{where}: expected a table")
        return None
    status = table.get("status")
    if not isinstance(status, str) or status not in STATUSES:
        errors.append(f"{where}: unknown status {status!r}; use one of {', '.join(STATUSES)}")
        return None
    required, optional = CLAIM_KEYS[status]
    keys(table, where, ("status", *required), optional, errors)
    claim = Claim(name, status)
    claim.evidence = strings(table, "evidence", where, errors) or []
    claim.premises = strings(table, "premises", where, errors, empty=True)
    if status in PROVED and claim.premises is None and "premises" in table:
        claim.premises = []
    claim.assumes = strings(table, "assumes", where, errors) or []
    claim.reason = text(table, "reason", where, errors)
    claim.note = text(table, "note", where, errors)
    issue = table.get("issue")
    if issue is not None:
        if isinstance(issue, bool) or not isinstance(issue, int) or issue <= 0:
            errors.append(f"{where}: `issue` must be a positive issue number")
        else:
            claim.issue = issue
    enforced = table.get("enforced_by")
    if enforced is not None:
        if not isinstance(enforced, list) or not enforced:
            errors.append(f"{where}: `enforced_by` must be a non-empty list of tables")
        else:
            for index, item in enumerate(enforced):
                at = f"{where} enforced_by[{index}]"
                if not keys(item, at, ("definition", "code"), (), errors):
                    continue
                definition, code = item.get("definition"), item.get("code")
                if not isinstance(definition, str) or not LEAN_NAME.fullmatch(definition) \
                        or not definition.startswith("VastitasKernel."):
                    errors.append(f"{at}: `definition` must be a fully qualified kernel definition "
                                  "under VastitasKernel")
                    definition = None
                if not isinstance(code, str) or not DIAGNOSTIC.fullmatch(code):
                    errors.append(f"{at}: `code` must be a diagnostic code such as E_METRIC")
                    code = None
                claim.enforced_by.append((definition, code))
    return claim


def parse_rule(value, where, root, errors):
    if value is None:
        return ("", "")
    match = LINK.fullmatch(value.strip()) if isinstance(value, str) else None
    if not match or ".." in match.group(2):
        errors.append(f"{where}: `specified_in` must be one Markdown link to a book chapter, "
                      "such as [Laws](adr/0001-mathematics-first-stdlib.md#laws)")
        return ("", "")
    label, target, anchor = match.group(1), match.group(2), match.group(3) or ""
    if not (root / "docs" / target).is_file():
        errors.append(f"{where}: `specified_in` names docs/{target}, which does not exist")
    return (paragraph(label), target + anchor)


def parse_property(identifier, table, prefix, where, root, errors):
    if not PROPERTY_ID.fullmatch(identifier):
        errors.append(f"{where}: invalid property id (use dot-separated lower-case words)")
    elif prefix and not identifier.startswith(prefix + "."):
        errors.append(f"{where}: the property id must begin with `{prefix}.`, the file's `id`")
    if not keys(table, where, *PROPERTY_KEYS, errors):
        return None
    values = {key: text(table, key, where, errors) for key in
              ("title", "subject", "statement", "example", "example_test", "example_not_executed")}
    title_rule(values["title"], where, errors)
    if values["subject"] and "`" in values["subject"]:
        errors.append(f"{where}: `subject` must not contain a backquote")
    if ("example_test" in table) == ("example_not_executed" in table):
        errors.append(f"{where}: give exactly one of `example_test` (the test that runs the example) "
                      "and `example_not_executed` (why no test runs it)")
    rule = parse_rule(table.get("specified_in"), where, root, errors)
    claims = []
    tables = table.get("claim")
    if tables is not None:
        if not isinstance(tables, dict) or not tables:
            errors.append(f"{where}: needs at least one `claim` table")
        else:
            for name, claim_table in tables.items():
                claim = parse_claim(name, claim_table, f'{where} claim.{name}', errors)
                if claim:
                    claims.append(claim)
    return Property(identifier, values["title"] or identifier, values["subject"] or "",
                    values["statement"] or "", rule, values["example"] or "",
                    values["example_test"], values["example_not_executed"], claims)


def parse_spec(root, path, errors):
    data = load_toml(root, path, errors)
    if data is None:
        return None
    for key in data:
        if key == "symbol":
            errors.append(f"{path}: `symbol` records are reserved for the std admission manifest "
                          "(#285), which has not defined their fields")
        elif key not in ("spec", "property"):
            errors.append(f"{path}: unknown table `{key}`")
    header = data.get("spec")
    if header is None:
        errors.append(f"{path}: missing the `[spec]` table")
        return None
    if not keys(header, f"{path} [spec]", ("id", "title", "subject", "description"), (), errors):
        return None
    values = {key: text(header, key, f"{path} [spec]", errors)
              for key in ("id", "title", "subject", "description")}
    if values["id"] and not FILE_ID.fullmatch(values["id"]):
        errors.append(f"{path} [spec]: invalid `id` (use lower-case words joined by hyphens)")
    title_rule(values["title"], f"{path} [spec]", errors)
    properties = []
    tables = data.get("property")
    if not isinstance(tables, dict) or not tables:
        errors.append(f"{path}: defines no property")
    else:
        for identifier, table in tables.items():
            item = parse_property(identifier, table, values["id"], f'{path} [property."{identifier}"]',
                                  root, errors)
            if item:
                properties.append(item)
    return Spec(path, values["id"] or path.stem, values["title"] or path.stem,
                values["subject"] or "", values["description"] or "", properties)


def parse_registry(root, errors):
    if not (root / REGISTRY).exists():
        return {}
    data = load_toml(root, REGISTRY, errors)
    if data is None:
        return {}
    for key in data:
        if key != "assumption":
            errors.append(f"{REGISTRY}: unknown table `{key}`")
    registry = {}
    entries = data.get("assumption", {})
    if not isinstance(entries, dict):
        errors.append(f"{REGISTRY}: `assumption` must be a table of assumptions")
        entries = {}
    for identifier, table in entries.items():
        where = f"{REGISTRY} [assumption.{identifier}]"
        if not SHORT_ID.fullmatch(identifier):
            errors.append(f"{where}: invalid assumption id (use lower-case words joined by hyphens)")
        if not keys(table, where, ("title", "statement"), (), errors):
            continue
        title, statement = text(table, "title", where, errors), text(table, "statement", where, errors)
        title_rule(title, where, errors)
        registry[identifier] = Assumption(identifier, title or identifier, statement or "")
    return registry


# Tests and the CI steps that run them.
#
# A Tested claim needs a CI step that runs each of its tests. The workflows are
# read with a subset of YAML that covers GitHub workflows, and each `run:` step
# with a model of the shell. Both are conservative: a form they do not model
# counts as not running a test, and so does a step that a condition, a
# continue-on-error flag or a filtered pull_request trigger may skip.

YAML_KEY = re.compile(r"""("(?:[^"\\]|\\.)*"|'(?:[^']|'')*'|[^\s#'"\-?:,\[\]{}][^#]*?|-[^\s#][^#]*?)\s*:(?:\s+|$)""")


class YamlLines:
    def __init__(self, text):
        self.lines = text.split("\n")
        self.index = 0

    def current(self):
        while self.index < len(self.lines):
            stripped = self.lines[self.index].strip()
            if stripped and not stripped.startswith("#"):
                return self.lines[self.index]
            self.index += 1
        return None


def yaml_indent(line):
    return len(line) - len(line.lstrip(" "))


def yaml_plain(text):
    match = re.search(r"\s#", text)
    return (text[:match.start()] if match else text).rstrip()


def yaml_scalar(text):
    text = text.strip()
    if len(text) > 1 and text[0] in "'\"" and text[-1] == text[0]:
        if text[0] == "'":
            return text[1:-1].replace("''", "'")
        return re.sub(r'\\(["\\/])', r"\1", text[1:-1])
    return yaml_plain(text)


def yaml_key(content):
    match = YAML_KEY.match(content)
    if not match:
        return None, None
    return yaml_scalar(match.group(1)), content[match.end():]


def yaml_node(lines, indent):
    line = lines.current()
    if line is None or yaml_indent(line) < indent:
        return None
    if line.lstrip().startswith("- ") or line.strip() == "-":
        return yaml_sequence(lines, yaml_indent(line))
    return yaml_mapping(lines, yaml_indent(line))


def yaml_mapping(lines, indent):
    result = {}
    while True:
        line = lines.current()
        if line is None or yaml_indent(line) != indent or line.lstrip().startswith("- "):
            return result
        key, rest = yaml_key(line.strip())
        if key is None:
            return result
        lines.index += 1
        result[key] = yaml_value(lines, indent, rest)


def yaml_value(lines, indent, rest):
    rest = rest.strip()
    if not rest or rest.startswith("#"):
        line = lines.current()
        if line is not None and (yaml_indent(line) > indent
                                 or yaml_indent(line) == indent and line.lstrip().startswith("- ")):
            return yaml_node(lines, yaml_indent(line))
        return None
    if rest[0] in "|>":
        header = yaml_plain(rest)
        return yaml_block(lines, indent, rest[0], "-" if "-" in header else "")
    if rest[0] in "'\"":
        return yaml_scalar(rest)
    if rest[0] == "[":
        text = yaml_plain(rest)
        inner = text[1:-1] if text.endswith("]") else "["
        if any(c in inner for c in "[]{}"):
            return text
        return [yaml_scalar(item) for item in inner.split(",") if item.strip()]
    if rest[0] == "{":
        return yaml_plain(rest)
    parts = [yaml_plain(rest)]
    while lines.index < len(lines.lines):
        line = lines.lines[lines.index]
        if not line.strip() or yaml_indent(line) <= indent or line.lstrip().startswith("#"):
            break
        parts.append(yaml_plain(line.strip()))
        lines.index += 1
    return " ".join(parts)


def yaml_block(lines, indent, style, chomping):
    body = []
    while lines.index < len(lines.lines):
        line = lines.lines[lines.index]
        if line.strip() and yaml_indent(line) <= indent:
            break
        body.append(line)
        lines.index += 1
    while body and not body[-1].strip():
        body.pop()
    margin = min((yaml_indent(line) for line in body if line.strip()), default=0)
    body = [line[margin:] for line in body]
    end = "" if chomping == "-" else "\n"
    if style == "|":
        return "\n".join(body) + end
    folded, previous = "", None
    for line in body:
        if not line:
            folded += "\n"
        elif line[0] == " " or previous is None or previous == "" or previous[0] == " ":
            folded += ("\n" if folded and not folded.endswith("\n") else "") + line
        else:
            folded += " " + line
        previous = line
    return folded + end


def yaml_sequence(lines, indent):
    items = []
    while True:
        line = lines.current()
        if line is None or yaml_indent(line) != indent or not (line.lstrip().startswith("- ")
                                                               or line.strip() == "-"):
            return items
        content = line.lstrip()[1:].lstrip()
        column = len(line) - len(content)
        lines.index += 1
        if not content:
            items.append(yaml_node(lines, indent + 1))
            continue
        key, rest = yaml_key(content)
        if key is None:
            items.append(yaml_scalar(content))
            continue
        item = {key: yaml_value(lines, column, rest)}
        item.update(yaml_mapping(lines, column))
        items.append(item)


def yaml_load(text):
    """Block mappings and sequences, plain, quoted and block scalars, and flow
    sequences of scalars; other flow collections stay text."""
    return yaml_node(YamlLines(text), 0)


FILTERS = ("paths", "paths-ignore", "branches", "branches-ignore", "types")


def every_pull_request(triggers):
    """Whether the `on:` value starts the workflow for every pull request."""
    if isinstance(triggers, str):
        return triggers == "pull_request"
    if isinstance(triggers, list):
        return "pull_request" in triggers
    if isinstance(triggers, dict) and "pull_request" in triggers:
        config = triggers["pull_request"]
        return config is None or isinstance(config, dict) and not any(key in config for key in FILTERS)
    return False


def may_skip(value):
    """Whether a `continue-on-error` value can be true."""
    return value is not None and str(value).strip().lower() != "false"


def run_steps(workflow):
    """(script, directory, pipefail) of each `run:` step that every pull request
    runs and whose failure fails the job. A step or job with `if:` or a
    `continue-on-error` that can be true does not count, and neither does a job
    that may run on Windows, whose default shell is PowerShell."""
    tree = yaml_load(workflow)
    if not isinstance(tree, dict) or not every_pull_request(tree.get("on")):
        return
    def defaults(table):
        run = ((table.get("defaults") or {}) if isinstance(table.get("defaults"), dict) else {}).get("run")
        return run if isinstance(run, dict) else {}
    top = defaults(tree)
    jobs = tree.get("jobs")
    for job in (jobs.values() if isinstance(jobs, dict) else []):
        if not isinstance(job, dict) or "if" in job or may_skip(job.get("continue-on-error")):
            continue
        if "windows" in f"{job.get('runs-on')} {job.get('strategy')}".lower():
            continue
        settings = dict(top, **defaults(job))
        for step in job.get("steps") or []:
            if not isinstance(step, dict) or not isinstance(step.get("run"), str):
                continue
            if "if" in step or may_skip(step.get("continue-on-error")):
                continue
            shell = step.get("shell", settings.get("shell"))
            if shell not in (None, "bash", "sh"):
                continue
            directory = step.get("working-directory", settings.get("working-directory", "."))
            yield step["run"], shell_directory(PurePosixPath("."), str(directory)), shell == "bash"


SHELL_PIECES = re.compile(r"&&|\|\||;;|\|&|>>|<<<|<<-?|>&|<&|&>|[;|&()<>]")
SHELL_CONTROL = {";", "&&", "||", "|", "&", "|&", ";;", "(", ")"}
SHELL_REDIRECTS = {">", ">>", "<", "<<", "<<-", "<<<", ">&", "<&", "&>"}
SHELL_ASSIGNMENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*=.*")
SHELL_PREFIXES = {"time", "command", "builtin", "nohup"}
SHELL_SKIPPED = SHELL_PREFIXES | {"then", "do", "else", "elif"}
SHELL_COMPOUNDS = {"if": "fi", "while": "done", "until": "done", "for": "done", "select": "done", "case": "esac"}
SHELL_CLOSERS = {"fi", "done", "esac", "}"}
# Commands after which the model no longer knows which commands run, or how a failure ends.
SHELL_STOPS = {"return", "source", ".", "eval", "trap", "alias", "shopt", "enable"}


def shell_tokens(line):
    lexer = shlex.shlex(line, posix=True, punctuation_chars=True)
    lexer.whitespace_split = True
    lexer.commenters = "#"
    tokens = []
    for token in lexer:
        if token and all(c in "();<>|&" for c in token):
            tokens += SHELL_PIECES.findall(token)
        else:
            tokens.append(token)
    return tokens


def shell_directory(directory, target):
    """`directory / target`, or None when the result is unknown."""
    if directory is None or not target or target.startswith(("/", "~")) or any(c in target for c in "$`*?"):
        return None
    return PurePosixPath(os.path.normpath(str(directory / target)))


def shell_cd(words, directory):
    """The directory after `cd WORDS` or `pushd WORDS`, or None when it is unknown."""
    arguments = [word for word in words[1:] if word not in ("-L", "-P")]
    if len(arguments) != 1 or arguments[0] == "-":
        return None
    return shell_directory(directory, arguments[0])


def shell_set(arguments, errexit, pipefail, switch_on):
    """errexit and pipefail after `set ARGUMENTS`. Unless `switch_on`, the
    options are only switched off."""
    pending = []
    for argument in arguments:
        if pending:
            on = pending.pop(0) == "-"
            if argument == "errexit" and (switch_on or not on):
                errexit = on
            elif argument == "pipefail" and (switch_on or not on):
                pipefail = on
            continue
        if argument in ("-", "--") or len(argument) < 2 or argument[0] not in "-+":
            break
        for letter in argument[1:]:
            if letter == "e" and (switch_on or argument[0] == "+"):
                errexit = argument[0] == "-"
            elif letter == "o":
                pending.append(argument[0])
    return errexit, pipefail


def shell_stops(words):
    """Whether the model loses track of the script after the command `words`."""
    if words[0] == "exit":
        return not (len(words) > 1 and words[1].isdigit() and int(words[1]) % 256)
    return words[0] in SHELL_STOPS or words[0] == "exec" and len(words) > 1


class ShellFrame:
    """An open compound command, group, subshell or substitution, with the list
    that contains it and the settings that a subshell restores."""

    def __init__(self, kind, closer, start, outer, saved):
        self.kind, self.closer, self.start, self.outer, self.saved = kind, closer, start, outer, saved


class ShellList:
    """The command list being read: the words of its current command, and the
    first command of its current pipeline and of its current pipeline element."""

    def __init__(self, start):
        self.words, self.pipeline, self.element = [], start, start
        self.andor = self.negated = self.piped = self.subshell = False


def shell_commands(script, directory=PurePosixPath("."), pipefail=False, errexit=True):
    """Each simple command of a shell script as (words, directory, counted).

    `pipefail` and `errexit` are the settings that the script starts with. A
    command counts when it runs whenever the script runs and its failure fails
    the script. A command does not count when it is inside `if`, `while`,
    `until`, `for`, `select`, `case` or a command substitution; when its pipeline
    is negated, in a list with `&&` or `||`, or in the background; when it comes
    before `|` without pipefail; when errexit is off; or when it follows a
    command that `shell_stops` names or a function definition. A group or
    subshell passes these conditions to the commands in it. `set` switches an
    option on only where it surely runs in the shell itself, and `cd` is followed
    only there: elsewhere the directory becomes None, unknown. A subshell
    restores both. Comments, quotes, redirections and here-document bodies are
    removed. A keyword that closes nothing, or a quote that never closes, stops
    the counting."""
    record, frames, heredoc, stopped = [], [], None, False
    current = ShellList(0)

    def mark(start):
        for command in record[start:]:
            command[2] = False

    def sure(token):
        return (not stopped and all(frame.kind == "subshell" for frame in frames) and not current.andor
                and not current.negated and not current.piped and token not in ("&&", "||", "&", "|", "|&"))

    def end(token):
        """End the current command, pipeline element or pipeline at `token`."""
        nonlocal directory, errexit, pipefail, stopped
        words, current.words = current.words, []
        if words and words[0] == "env":
            words = words[1:]
            while words and (SHELL_ASSIGNMENT.fullmatch(words[0]) or words[0].startswith("-")):
                words = words[2:] if words[0] in ("-u", "-C", "-S") else words[1:]
        if words and words[0] in ("cd", "pushd", "popd"):
            directory = shell_cd(words, directory) if sure(token) and words[0] != "popd" else None
        elif words:
            if words[0] == "set":
                errexit, pipefail = shell_set(words[1:], errexit, pipefail, sure(token))
            conditional = any(frame.kind in ("compound", "substitution") for frame in frames)
            record.append([words, directory, errexit and not stopped and not conditional])
            stopped = stopped or shell_stops(words)
        if current.subshell and not errexit or token in ("|", "|&") and not pipefail:
            mark(current.element)
        current.subshell, current.element = False, len(record)
        if token in ("|", "|&"):
            current.piped = True
            return
        if current.negated or current.andor or token in ("&&", "||", "&"):
            mark(current.pipeline)
        current.pipeline, current.negated, current.piped = len(record), False, False
        current.andor = token in ("&&", "||")

    def open_frame(kind, closer):
        nonlocal current
        frames.append(ShellFrame(kind, closer, len(record), current, (errexit, pipefail, directory)))
        current = ShellList(len(record))

    def close_frame():
        nonlocal current, errexit, pipefail, directory
        frame = frames.pop()
        current = frame.outer
        if frame.kind in ("subshell", "substitution"):
            errexit, pipefail, directory = frame.saved
            current.subshell = frame.kind == "subshell"

    lines = script.replace("\\\n", " ").split("\n")
    number = 0
    while number < len(lines):
        line, number = lines[number], number + 1
        if heredoc is not None:
            if line.strip() == heredoc:
                heredoc = None
            continue
        tokens = None
        while tokens is None:
            try:
                tokens = shell_tokens(line)
            except ValueError:
                if number == len(lines):
                    break
                line, number = line + "\n" + lines[number], number + 1
        if tokens is None:
            stopped = True
            break
        if not tokens:
            continue
        if tokens[-1] not in ("&&", "||", "|", "|&"):
            tokens.append(";")
        target, position = None, 0
        while position < len(tokens):
            token, previous, position = tokens[position], tokens[position - 1] if position else "", position + 1
            if target is not None:
                if token == "(":
                    open_frame("substitution", ")")
                elif target in ("<<", "<<-"):
                    heredoc = token.lstrip("-")
                target = None
            elif token in SHELL_REDIRECTS:
                if current.words and current.words[-1].isdigit():
                    current.words.pop()
                target = token
            elif token == "(" and len(current.words) == 1 and tokens[position:position + 1] == [")"]:
                stopped, current.words, position = True, [], position + 1
            elif token == "(":
                open_frame("substitution" if current.words or previous.endswith("$") else "subshell", ")")
            elif token == ")":
                if frames and frames[-1].closer == "esac":
                    current.words = []
                elif frames and frames[-1].closer == ")":
                    end(";")
                    close_frame()
                else:
                    stopped = True
            elif token in SHELL_CONTROL:
                end(token)
            elif current.words:
                current.words.append(token)
            elif token in SHELL_COMPOUNDS:
                open_frame("compound", SHELL_COMPOUNDS[token])
            elif token == "{":
                open_frame("group", "}")
            elif token in SHELL_CLOSERS:
                if frames and frames[-1].closer == token:
                    close_frame()
                else:
                    stopped = True
            elif token == "!":
                current.negated = True
            elif token == "function":
                stopped = True
            elif token not in SHELL_SKIPPED and not SHELL_ASSIGNMENT.fullmatch(token):
                current.words.append(token)
    if frames:
        mark(frames[0].start)
    for words, where, counted in record:
        yield words, where, counted


def option(argument, items, short, long):
    """The value of `-s VALUE`, `-sVALUE`, `--long VALUE` or `--long=VALUE`, or None."""
    if argument == short or long and argument == long:
        return next(items, "")
    if short and argument.startswith(short) and len(argument) > len(short) and not argument.startswith("--"):
        return argument[len(short):]
    if long and argument.startswith(long + "="):
        return argument[len(long) + 1:]
    return None


CARGO_VALUES = {"--bin", "--example", "--bench", "--features", "-F", "--target", "--target-dir", "-j", "--jobs",
                "--profile", "--color", "--message-format", "--exclude", "-Z", "--config"}
CARGO_TARGETS = {"--lib", "--bins", "--bin", "--examples", "--example", "--benches", "--bench", "--doc"}


@dataclass
class CargoRun:
    every_test: bool
    targets: set
    ignored: str
    filters: list
    skips: list
    exact: bool
    runs_nothing: bool

    def runs(self, stem, name, ignored):
        if self.runs_nothing or not (self.every_test or stem in self.targets):
            return False
        if ignored and self.ignored == "exclude" or not ignored and self.ignored == "only":
            return False

        def matches(pattern):
            return name == pattern if self.exact else pattern in name

        if any(matches(skip) for skip in self.skips):
            return False
        return not self.filters or any(matches(item) for item in self.filters)


def cargo_run(arguments, package=None):
    """The tests that `cargo test ARGUMENTS` runs in the root package `package`."""
    split = arguments.index("--") if "--" in arguments else len(arguments)
    before, after = arguments[:split], arguments[split + 1:]
    run = CargoRun(False, set(), "exclude", [], [], False, False)
    selected, items = False, iter(before)
    for argument in items:
        name, _, attached = argument.partition("=") if argument.startswith("--") else (argument, "", "")
        value = option(argument, items, "-p", "--package")
        if value is not None:
            if value != package:
                run.runs_nothing = True
        elif name == "--manifest-path":
            value = attached or next(items, "")
            if os.path.normpath(value) != "Cargo.toml":
                run.runs_nothing = True
        elif name == "--no-run":
            run.runs_nothing = True
        elif name in ("--all-targets", "--tests"):
            run.every_test = selected = True
        elif name == "--test":
            selected = True
            run.targets.add(attached or next(items, ""))
        elif name in CARGO_TARGETS:
            selected = True
            if name in CARGO_VALUES and not attached:
                next(items, None)
        elif name in CARGO_VALUES and not attached:
            next(items, None)
        elif not argument.startswith("-"):
            run.filters.append(argument)
    if not selected:
        run.every_test = True
    items = iter(after)
    for argument in items:
        skip = option(argument, items, None, "--skip")
        if skip is not None:
            run.skips.append(skip)
        elif argument == "--ignored":
            run.ignored = "only"
        elif argument == "--include-ignored":
            run.ignored = "include"
        elif argument == "--exact":
            run.exact = True
        elif argument == "--list":
            run.runs_nothing = True
        elif argument in ("--test-threads", "--format", "--color", "-Z", "--logfile", "--shuffle-seed"):
            next(items, None)
        elif not argument.startswith("-"):
            run.filters.append(argument)
    return run


@dataclass
class DiscoverRun:
    start: PurePosixPath
    pattern: str
    selections: list

    def runs(self, path, test_class, method):
        path = PurePosixPath(path)
        if path.parent != self.start or not fnmatch.fnmatchcase(path.name, self.pattern):
            return False
        full = f"{path.stem}.{test_class}.{method}"
        return not self.selections or any(
            fnmatch.fnmatchcase(full, item) if "*" in item else item in full for item in self.selections)


def discover_run(arguments, directory):
    """The tests that `python3 -m unittest discover ARGUMENTS` runs from `directory`."""
    start, pattern, positional, selections = ".", "test*.py", [], []
    items = iter(arguments)
    for argument in items:
        for short, long in (("-s", "--start-directory"), ("-p", "--pattern"),
                            ("-t", "--top-level-directory"), ("-k", None)):
            value = option(argument, items, short, long)
            if value is not None:
                if short == "-s":
                    start = value
                elif short == "-p":
                    pattern = value
                elif short == "-k":
                    selections.append(value)
                break
        else:
            if not argument.startswith("-"):
                positional.append(argument)
    if positional:
        start = positional[0]
    if len(positional) > 1:
        pattern = positional[1]
    resolved = shell_directory(directory, start)
    return DiscoverRun(resolved, pattern, selections) if resolved is not None else None


RUST_RAW = re.compile(r'(b?)r(#*)"')
RUST_CHAR = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]{1,6}\}|.)|[^\\'\n])'")
RUST_TOKEN = re.compile(r"#!?\[|\bmod\s+([A-Za-z_]\w*)\s*\{|\bfn\s+([A-Za-z_]\w*)|[{};]")
RUST_NAME = re.compile(r"\s*([A-Za-z_][\w:]*)")


def rust_blank(source):
    """The source without comments, with the contents of string and character
    literals removed. Newlines stay."""
    out, i, n = [], 0, len(source)

    def identifier_before(index):
        return index > 0 and (source[index - 1].isalnum() or source[index - 1] == "_")

    while i < n:
        if source.startswith("//", i):
            end = source.find("\n", i)
            i = n if end < 0 else end
            continue
        if source.startswith("/*", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if source.startswith("/*", i):
                    depth, i = depth + 1, i + 2
                elif source.startswith("*/", i):
                    depth, i = depth - 1, i + 2
                else:
                    out.append("\n" if source[i] == "\n" else "")
                    i += 1
            continue
        raw = RUST_RAW.match(source, i)
        if raw and not identifier_before(i):
            end = source.find('"' + raw.group(2), raw.end())
            end = n if end < 0 else end + 1 + len(raw.group(2))
            out.append('""' + "\n" * source.count("\n", i, end))
            i = end
            continue
        if source[i] == '"' or source.startswith('b"', i) and not identifier_before(i):
            j = i + (2 if source[i] == "b" else 1)
            while j < n and source[j] != '"':
                j += 2 if source[j] == "\\" else 1
            out.append('""' + "\n" * source.count("\n", i, j))
            i = j + 1
            continue
        if source[i] == "'":
            match = RUST_CHAR.match(source, i)
            if match:
                out.append("' '")
                i = match.end()
                continue
        out.append(source[i])
        i += 1
    return "".join(out)


def rust_closing(text, start):
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "[":
            depth += 1
        elif text[index] == "]":
            depth -= 1
            if depth == 0:
                return index
    return len(text) - 1


def rust_attribute(attribute):
    match = RUST_NAME.match(attribute)
    return match.group(1) if match else ""


def rust_conditional(attributes):
    """Whether attributes compile their item only under a configuration other than `cfg(test)`."""
    return any(rust_attribute(a) == "cfg" and re.sub(r"\s", "", a) != "cfg(test)" for a in attributes)


def rust_tests(source):
    """Map the libtest name of each `#[test]` function, such as `a::b`, to
    (ignored, conditional). A test is ignored under `#[ignore]` or a `cfg_attr`
    that can add `ignore`. It is conditional under `#[cfg(...)]` other than
    `cfg(test)`, on the function or on an enclosing module or file."""
    text = rust_blank(source)
    found, stack, pending, whole_file, index = {}, [], [], False, 0
    while True:
        match = RUST_TOKEN.search(text, index)
        if not match:
            return found
        token, index = match.group(0), match.end()
        if token.startswith("#"):
            end = rust_closing(text, match.end() - 1)
            body, index = text[match.end():end], end + 1
            if token != "#![":
                pending.append(body)
            elif rust_conditional([body]):
                if stack:
                    stack[-1] = (stack[-1][0], stack[-1][1], True)
                else:
                    whole_file = True
            continue
        if match.group(1):
            stack.append((True, match.group(1), rust_conditional(pending)))
        elif match.group(2):
            if any(re.sub(r"\s", "", a) == "test" for a in pending):
                path = "::".join([frame[1] for frame in stack if frame[0]] + [match.group(2)])
                ignored = any(rust_attribute(a) == "ignore"
                              or rust_attribute(a) == "cfg_attr" and re.search(r"\bignore\b", a) for a in pending)
                found[path] = (bool(ignored),
                               whole_file or any(frame[2] for frame in stack) or rust_conditional(pending))
        elif token == "{":
            stack.append((False, None, rust_conditional(pending)))
        elif token == "}" and stack:
            stack.pop()
        pending = []


def python_tests(source):
    """(class, method) of the test methods of the unittest.TestCase classes of a
    module, mapped to whether a decorator skips the method or its class
    unconditionally: `skip`, `skipIf(True, …)` or `skipUnless(False, …)`."""
    classes = {}
    for node in ast.parse(source).body:
        if isinstance(node, ast.ClassDef):
            classes[node.name] = node

    def base_names(node):
        return [base.attr if isinstance(base, ast.Attribute) else getattr(base, "id", "") for base in node.bases]

    def test_case(name, seen=()):
        node = classes.get(name)
        return node is not None and name not in seen and any(
            base in ("TestCase", "IsolatedAsyncioTestCase") or test_case(base, seen + (name,))
            for base in base_names(node))

    def skipped(node):
        for decorator in node.decorator_list:
            call = decorator if isinstance(decorator, ast.Call) else None
            target = call.func if call else decorator
            name = target.attr if isinstance(target, ast.Attribute) else getattr(target, "id", "")
            if name == "skip":
                return True
            if call and name in ("skipIf", "skipUnless") and call.args and isinstance(call.args[0], ast.Constant) \
                    and bool(call.args[0].value) == (name == "skipIf"):
                return True
        return False

    def methods(name, seen=()):
        node = classes.get(name)
        if node is None or name in seen:
            return {}
        found = {}
        for base in reversed(base_names(node)):
            found.update(methods(base, seen + (name,)))
        for item in node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name.startswith("test"):
                found[item.name] = skipped(item)
        return found

    tests = {}
    for name, node in classes.items():
        if test_case(name):
            for method, skip in methods(name).items():
                tests[(name, method)] = skip or skipped(node)
    return tests


def script_target(words, directory):
    """The script that a command runs as `bash SCRIPT`, `sh SCRIPT` or `SCRIPT`, or None."""
    if words and words[0] in ("bash", "sh"):
        arguments = [word for word in words[1:] if not word.startswith("-")]
        return shell_directory(directory, arguments[0]) if arguments else None
    if words and "/" in words[0]:
        return shell_directory(directory, words[0])
    return None


class Repository:
    """The tests, the CI steps, the kernel regressions and the diagnostic codes of a checkout."""

    def __init__(self, root):
        self.root = root
        self.cargo, self.discover, self.regression_steps = [], [], 0
        package = None
        if (root / "Cargo.toml").is_file():
            try:
                package = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8")).get("package", {}).get("name")
            except tomllib.TOMLDecodeError:
                package = None
        directory = root / WORKFLOWS
        workflows = sorted(directory.glob("*.yml")) + sorted(directory.glob("*.yaml")) if directory.is_dir() else []
        for path in workflows:
            for script, start, pipefail in run_steps(path.read_text(encoding="utf-8")):
                for words, where, counted in shell_commands(script, start, pipefail):
                    if counted:
                        self.add(words, where, package)
        self.regressions = set()
        if (root / REGRESSIONS).is_file():
            script = (root / REGRESSIONS).read_text(encoding="utf-8")
            for words, _, counted in shell_commands(script, errexit=False):
                if counted and words[:4] == ["lake", "-d", "lean-kernel", "build"]:
                    self.regressions.update(item for item in words[4:] if LEAN_NAME.fullmatch(item))
        self.codes = set()
        if (root / DIAGNOSTICS).is_file():
            self.codes = set(re.findall(r"`(E_[A-Z0-9_]+)`", (root / DIAGNOSTICS).read_text(encoding="utf-8")))
        self._rust, self._python = {}, {}

    def add(self, words, directory, package):
        if os.path.basename(words[0]) == "cargo" and words[1:2] == ["test"]:
            if directory == PurePosixPath("."):
                self.cargo.append(cargo_run(words[2:], package))
        elif os.path.basename(words[0]) in ("python", "python3"):
            rest = words[1:]
            while rest and rest[0].startswith("-") and rest[0] != "-m":
                rest = rest[1:]
            if rest[:3] == ["-m", "unittest", "discover"] and directory is not None:
                run = discover_run(rest[3:], directory)
                if run is not None:
                    self.discover.append(run)
        elif script_target(words, directory) == PurePosixPath(REGRESSIONS):
            self.regression_steps += 1

    def rust(self, path):
        if path not in self._rust:
            file = self.root / path
            self._rust[path] = rust_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
        return self._rust[path]

    def python(self, path):
        if path not in self._python:
            file = self.root / path
            try:
                self._python[path] = python_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
            except SyntaxError:
                self._python[path] = None
        return self._python[path]

    def check_test(self, item, where, errors):
        """Check one Tested reference: the test exists and a CI step runs it."""
        if match := RUST_TEST.fullmatch(item):
            path, name = match.groups()
            tests = self.rust(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist")
            elif name not in tests:
                errors.append(f"{where}: {path} has no #[test] function `{name}`")
            elif tests[name][1]:
                errors.append(f"{where}: `{item}` is compiled only under a #[cfg(...)] condition, "
                              "so it does not count as run")
            elif not any(run.runs(PurePosixPath(path).stem, name, tests[name][0]) for run in self.cargo):
                if tests[name][0]:
                    errors.append(f"{where}: `{item}` is #[ignore]d, and no CI step passes --ignored for it")
                else:
                    errors.append(f"{where}: no CI step runs `{item}`")
        elif match := PYTHON_TEST.fullmatch(item):
            path, test_class, method = match.groups()
            tests = self.python(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist or does not parse")
            elif (test_class, method) not in tests:
                errors.append(f"{where}: {path} has no unittest test method `{test_class}.{method}`")
            elif tests[(test_class, method)]:
                errors.append(f"{where}: `{item}` is skipped unconditionally")
            elif not any(run.runs(path, test_class, method) for run in self.discover):
                errors.append(f"{where}: no CI step runs `{item}`")
        elif LEAN_NAME.fullmatch(item):
            if item not in self.regressions:
                errors.append(f"{where}: `{item}` is not a module that {REGRESSIONS} builds")
            elif not module_source(self.root, item):
                errors.append(f"{where}: the regression module `{item}` has no source file")
            elif not self.regression_steps:
                errors.append(f"{where}: no CI step runs {REGRESSIONS}")
        else:
            errors.append(f"{where}: `{item}` is not a test reference: use tests/<file>.rs::<function>, "
                          "<directory>/test_<name>.py::<Class>::<method> or a kernel regression module")

    def tested_form(self, item):
        return bool(RUST_TEST.fullmatch(item) or PYTHON_TEST.fullmatch(item) or item in self.regressions)


def module_path(module):
    top = module.split(".", 1)[0]
    if top not in SOURCES:
        return None
    return PurePosixPath(SOURCES[top], *module.split(".")).with_suffix(".lean")


def module_source(root, module):
    path = module_path(module)
    return path is not None and (root / path).is_file()


