def paragraph(value):
    return " ".join(value.split())


def inline(value):
    """Escape HTML outside code spans, so that text such as Pair<Int> renders as written."""
    parts = value.split("`")
    for index in range(0, len(parts), 2):
        parts[index] = parts[index].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return "`".join(parts)


def keys(value, where, required, optional, errors):
    if not isinstance(value, dict):
        errors.append(f"{where}: expected a table")
        return False
    for key in required:
        if key not in value:
            errors.append(f"{where}: missing `{key}`")
    for key in value:
        if key not in required and key not in optional:
            errors.append(f"{where}: unknown key `{key}`")
    return True


def text(value, key, where, errors):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, str) or not item.strip():
        errors.append(f"{where}: `{key}` must be a non-empty string")
        return None
    if item.count("`") % 2:
        errors.append(f"{where}: `{key}` has an unmatched backquote")
    return paragraph(item)


def strings(value, key, where, errors, empty=False):
    item = value.get(key)
    if item is None:
        return None
    if not isinstance(item, list) or not all(isinstance(x, str) and x.strip() for x in item):
        errors.append(f"{where}: `{key}` must be a list of non-empty strings")
        return None
    if not item and not empty:
        errors.append(f"{where}: `{key}` must not be empty")
    if any(x.count("`") % 2 for x in item):
        errors.append(f"{where}: an item of `{key}` has an unmatched backquote")
    repeated = sorted({x for x in item if item.count(x) > 1})
    if repeated:
        errors.append(f"{where}: `{key}` repeats {', '.join(repeated)}")
    return [paragraph(x) for x in item]


def title_rule(title, where, errors):
    """Titles appear in headings, tables and link text, so they hold no markup."""
    if title and any(c in title for c in "|[]<>`"):
        errors.append(f"{where}: `title` must not contain `|`, `[`, `]`, `<`, `>` or a backquote")


def load_toml(root, path, errors):
    try:
        with open(root / path, "rb") as file:
            return tomllib.load(file)
    except OSError as error:
        errors.append(f"{path}: cannot read: {error}")
    except tomllib.TOMLDecodeError as error:
        errors.append(f"{path}: invalid TOML: {error}")
    return None


def parse_claim(name, table, where, errors):
    if not SHORT_ID.fullmatch(name):
        errors.append(f"{where}: invalid claim name (use lower-case words joined by hyphens)")
    if not isinstance(table, dict):
        errors.append(f"{where}: expected a table")
        return None
    status = table.get("status")
    if not isinstance(status, str) or status not in STATUSES:
        errors.append(f"{where}: unknown status {status!r}; use one of {', '.join(STATUSES)}")
        return None
    required, optional = CLAIM_KEYS[status]
    keys(table, where, ("status", *required), optional, errors)
    claim = Claim(name, status)
    claim.evidence = strings(table, "evidence", where, errors) or []
    claim.premises = strings(table, "premises", where, errors, empty=True)
    if status in PROVED and claim.premises is None and "premises" in table:
        claim.premises = []
    claim.assumes = strings(table, "assumes", where, errors) or []
    claim.reason = text(table, "reason", where, errors)
    claim.note = text(table, "note", where, errors)
    issue = table.get("issue")
    if issue is not None:
        if isinstance(issue, bool) or not isinstance(issue, int) or issue <= 0:
            errors.append(f"{where}: `issue` must be a positive issue number")
        else:
            claim.issue = issue
    enforced = table.get("enforced_by")
    if enforced is not None:
        if not isinstance(enforced, list) or not enforced:
            errors.append(f"{where}: `enforced_by` must be a non-empty list of tables")
        else:
            for index, item in enumerate(enforced):
                at = f"{where} enforced_by[{index}]"
                if not keys(item, at, ("definition", "code"), (), errors):
                    continue
                definition, code = item.get("definition"), item.get("code")
                if not isinstance(definition, str) or not LEAN_NAME.fullmatch(definition) \
                        or not definition.startswith("VastitasKernel."):
                    errors.append(f"{at}: `definition` must be a fully qualified kernel definition "
                                  "under VastitasKernel")
                    definition = None
                if not isinstance(code, str) or not DIAGNOSTIC.fullmatch(code):
                    errors.append(f"{at}: `code` must be a diagnostic code such as E_METRIC")
                    code = None
                claim.enforced_by.append((definition, code))
    return claim


def parse_rule(value, where, root, errors):
    if value is None:
        return ("", "")
    match = LINK.fullmatch(value.strip()) if isinstance(value, str) else None
    if not match or ".." in match.group(2):
        errors.append(f"{where}: `specified_in` must be one Markdown link to a book chapter, "
                      "such as [Laws](adr/0001-mathematics-first-stdlib.md#laws)")
        return ("", "")
    label, target, anchor = match.group(1), match.group(2), match.group(3) or ""
    if not (root / "docs" / target).is_file():
        errors.append(f"{where}: `specified_in` names docs/{target}, which does not exist")
    return (paragraph(label), target + anchor)


def parse_property(identifier, table, prefix, where, root, errors):
    if not PROPERTY_ID.fullmatch(identifier):
        errors.append(f"{where}: invalid property id (use dot-separated lower-case words)")
    elif prefix and not identifier.startswith(prefix + "."):
        errors.append(f"{where}: the property id must begin with `{prefix}.`, the file's `id`")
    if not keys(table, where, *PROPERTY_KEYS, errors):
        return None
    values = {key: text(table, key, where, errors) for key in
              ("title", "subject", "statement", "example", "example_test", "example_not_executed")}
    title_rule(values["title"], where, errors)
    if values["subject"] and "`" in values["subject"]:
        errors.append(f"{where}: `subject` must not contain a backquote")
    if ("example_test" in table) == ("example_not_executed" in table):
        errors.append(f"{where}: give exactly one of `example_test` (the test that runs the example) "
                      "and `example_not_executed` (why no test runs it)")
    rule = parse_rule(table.get("specified_in"), where, root, errors)
    claims = []
    tables = table.get("claim")
    if tables is not None:
        if not isinstance(tables, dict) or not tables:
            errors.append(f"{where}: needs at least one `claim` table")
        else:
            for name, claim_table in tables.items():
                claim = parse_claim(name, claim_table, f'{where} claim.{name}', errors)
                if claim:
                    claims.append(claim)
    return Property(identifier, values["title"] or identifier, values["subject"] or "",
                    values["statement"] or "", rule, values["example"] or "",
                    values["example_test"], values["example_not_executed"], claims)


def parse_spec(root, path, errors):
    data = load_toml(root, path, errors)
    if data is None:
        return None
    for key in data:
        if key == "symbol":
            errors.append(f"{path}: `symbol` records are reserved for the std admission manifest "
                          "(#285), which has not defined their fields")
        elif key not in ("spec", "property"):
            errors.append(f"{path}: unknown table `{key}`")
    header = data.get("spec")
    if header is None:
        errors.append(f"{path}: missing the `[spec]` table")
        return None
    if not keys(header, f"{path} [spec]", ("id", "title", "subject", "description"), (), errors):
        return None
    values = {key: text(header, key, f"{path} [spec]", errors)
              for key in ("id", "title", "subject", "description")}
    if values["id"] and not FILE_ID.fullmatch(values["id"]):
        errors.append(f"{path} [spec]: invalid `id` (use lower-case words joined by hyphens)")
    title_rule(values["title"], f"{path} [spec]", errors)
    properties = []
    tables = data.get("property")
    if not isinstance(tables, dict) or not tables:
        errors.append(f"{path}: defines no property")
    else:
        for identifier, table in tables.items():
            item = parse_property(identifier, table, values["id"], f'{path} [property."{identifier}"]',
                                  root, errors)
            if item:
                properties.append(item)
    return Spec(path, values["id"] or path.stem, values["title"] or path.stem,
                values["subject"] or "", values["description"] or "", properties)


def parse_registry(root, errors):
    if not (root / REGISTRY).exists():
        return {}
    data = load_toml(root, REGISTRY, errors)
    if data is None:
        return {}
    for key in data:
        if key != "assumption":
            errors.append(f"{REGISTRY}: unknown table `{key}`")
    registry = {}
    entries = data.get("assumption", {})
    if not isinstance(entries, dict):
        errors.append(f"{REGISTRY}: `assumption` must be a table of assumptions")
        entries = {}
    for identifier, table in entries.items():
        where = f"{REGISTRY} [assumption.{identifier}]"
        if not SHORT_ID.fullmatch(identifier):
            errors.append(f"{where}: invalid assumption id (use lower-case words joined by hyphens)")
        if not keys(table, where, ("title", "statement"), (), errors):
            continue
        title, statement = text(table, "title", where, errors), text(table, "statement", where, errors)
        title_rule(title, where, errors)
        registry[identifier] = Assumption(identifier, title or identifier, statement or "")
    return registry


# Tests and the CI steps that run them.
#
# A Tested claim needs a CI step that runs each of its tests. The workflows are
# read with a subset of YAML that covers GitHub workflows, and each `run:` step
# only as far as its lines are plain. Both are conservative: a form they do not
# read counts as not running a test, and so does a step that a condition, a
# continue-on-error flag or a filtered pull_request trigger may skip.

YAML_KEY = re.compile(r"([A-Za-z0-9_][A-Za-z0-9_.-]*)[ ]*:(?:[ ]+|$)")


YAML_QUOTED = re.compile(r"""(?:"(?:[^"\\]|\\.)*"|'(?:[^']|'')*')[ ]*(?:#.*)?""")


class YamlError(ValueError):
    """A workflow form that the YAML subset does not read."""


class Folded(str):
    """A scalar that YAML folds from several lines."""


class YamlLines:
    def __init__(self, text):
        self.lines = text.split("\n")
        self.index = 0

    def current(self):
        while self.index < len(self.lines):
            line = self.lines[self.index]
            if line.strip() and not line.strip().startswith("#"):
                if "\t" in line[:len(line) - len(line.lstrip())]:
                    raise YamlError("a tab in indentation")
                return line
            self.index += 1
        return None


def yaml_indent(line):
    return len(line) - len(line.lstrip(" "))


def yaml_plain(text):
    match = re.search(r"\s#", text)
    return (text[:match.start()] if match else text).rstrip()


def yaml_scalar(text):
    text = text.strip()
    if len(text) > 1 and text[0] in "'\"" and text[-1] == text[0]:
        if text[0] == "'":
            return text[1:-1].replace("''", "'")
        return re.sub(r'\\(["\\/])', r"\1", text[1:-1])
    return yaml_plain(text)


def yaml_key(content):
    """The plain key of a mapping entry and the text after it. A quoted,
    explicit, tagged, anchored or merge key raises YamlError."""
    match = YAML_KEY.match(content)
    if not match:
        raise YamlError(f"an unread mapping key in {content!r}")
    return match.group(1), content[match.end():]


def yaml_node(lines, indent):
    line = lines.current()
    if line is None or yaml_indent(line) < indent:
        return None
    if line.lstrip().startswith("- ") or line.strip() == "-":
        return yaml_sequence(lines, yaml_indent(line))
    return yaml_mapping(lines, yaml_indent(line))


def yaml_mapping(lines, indent):
    result = {}
    while True:
        line = lines.current()
        if line is None or yaml_indent(line) != indent or line.lstrip().startswith("- "):
            return result
        key, rest = yaml_key(line.strip())
        if key in result:
            raise YamlError(f"a repeated key {key!r}")
        lines.index += 1
        result[key] = yaml_value(lines, indent, rest)


def yaml_value(lines, indent, rest):
    rest = rest.strip()
    if not rest or rest.startswith("#"):
        line = lines.current()
        if line is not None and (yaml_indent(line) > indent
                                 or yaml_indent(line) == indent and line.lstrip().startswith("- ")):
            return yaml_node(lines, yaml_indent(line))
        return None
    if rest[0] in "|>":
        header = yaml_plain(rest)
        return yaml_block(lines, indent, rest[0], "-" if "-" in header else "")
    if rest[0] in "'\"":
        return yaml_scalar(rest)
    if rest[0] == "[":
        text = yaml_plain(rest)
        inner = text[1:-1] if text.endswith("]") else "["
        if any(c in inner for c in "[]{}"):
            return text
        return [yaml_scalar(item) for item in inner.split(",") if item.strip()]
    if rest[0] == "{":
        return yaml_plain(rest)
    parts = [yaml_plain(rest)]
    while lines.index < len(lines.lines):
        line = lines.lines[lines.index]
        if not line.strip() or yaml_indent(line) <= indent or line.lstrip().startswith("#"):
            break
        parts.append(yaml_plain(line.strip()))
        lines.index += 1
    return Folded(" ".join(parts)) if len(parts) > 1 else parts[0]


def yaml_block(lines, indent, style, chomping):
    body = []
    while lines.index < len(lines.lines):
        line = lines.lines[lines.index]
        if line.strip() and yaml_indent(line) <= indent:
            break
        body.append(line)
        lines.index += 1
    while body and not body[-1].strip():
        body.pop()
    margin = min((yaml_indent(line) for line in body if line.strip()), default=0)
    body = [line[margin:] for line in body]
    end = "" if chomping == "-" else "\n"
    if style == "|":
        return "\n".join(body) + end
    return Folded(yaml_fold(body) + end)


def yaml_fold(body):
    folded, previous = "", None
    for line in body:
        if not line:
            folded += "\n"
        elif line[0] == " " or previous is None or previous == "" or previous[0] == " ":
            folded += ("\n" if folded and not folded.endswith("\n") else "") + line
        else:
            folded += " " + line
        previous = line
    return folded


def yaml_sequence(lines, indent):
    items = []
    while True:
        line = lines.current()
        if line is None or yaml_indent(line) != indent or not (line.lstrip().startswith("- ")
                                                               or line.strip() == "-"):
            return items
        content = line.lstrip()[1:].lstrip()
        column = len(line) - len(content)
        lines.index += 1
        if not content:
            items.append(yaml_node(lines, indent + 1))
            continue
        if not YAML_KEY.match(content):
            if not YAML_QUOTED.fullmatch(content) and re.search(r":(?:[ ]|$)", content):
                raise YamlError(f"an unread mapping key in {content!r}")
            items.append(yaml_scalar(content))
            continue
        key, rest = yaml_key(content)
        item = {key: yaml_value(lines, column, rest)}
        others = yaml_mapping(lines, column)
        if key in others:
            raise YamlError(f"a repeated key {key!r}")
        item.update(others)
        items.append(item)


def yaml_load(text):
    """Block mappings and sequences, plain, quoted and block scalars, and flow
    sequences of scalars; other flow collections stay text. A scalar folded
    from several lines is Folded. YamlError reports a form outside the subset,
    including a repeated key, which GitHub rejects."""
    return yaml_node(YamlLines(text), 0)


FILTERS = ("paths", "paths-ignore", "branches", "branches-ignore", "types")


def every_pull_request(triggers):
    """Whether the `on:` value starts the workflow for every pull request."""
    if isinstance(triggers, str):
        return triggers == "pull_request"
    if isinstance(triggers, list):
        return "pull_request" in triggers
    if isinstance(triggers, dict) and "pull_request" in triggers:
        config = triggers["pull_request"]
        return config is None or isinstance(config, dict) and not any(key in config for key in FILTERS)
    return False


def may_skip(value):
    """Whether a `continue-on-error` value can be true."""
    return value is not None and str(value).strip().lower() != "false"


def unix_job(job):
    """Whether every runner that `job` may use is a GitHub-hosted Linux or macOS
    runner, `ubuntu-…` or `macos-…`, where a `run:` step uses bash by default.
    A `${{ matrix.KEY }}` runner takes the literal values of KEY in the job's
    matrix, with those that `include` adds; a matrix with `exclude` is not
    read."""
    labels = job.get("runs-on")
    if isinstance(labels, str):
        match = re.fullmatch(r"\$\{\{\s*matrix\.([A-Za-z0-9_-]+)\s*\}\}", labels.strip())
        if match:
            strategy = job.get("strategy")
            matrix = strategy.get("matrix") if isinstance(strategy, dict) else None
            include = matrix.get("include") or [] if isinstance(matrix, dict) and "exclude" not in matrix else None
            if not isinstance(include, list) or not all(isinstance(entry, dict) for entry in include):
                return False
            values = matrix.get(match.group(1), [])
            labels = (values if isinstance(values, list) else [values]) + [
                entry[match.group(1)] for entry in include if match.group(1) in entry]
        else:
            labels = [labels]
    return isinstance(labels, list) and bool(labels) and all(
        isinstance(label, str) and label.startswith(("ubuntu-", "macos-")) for label in labels)


# Variables that change how bash starts, reads or finds commands, how programs
# load, or how cargo and Python build and run tests: a test runner, a compiler
# wrapper, a cross target or a Python path.
SHELL_ENVIRONMENT = {"BASH_ENV", "BASHOPTS", "CDPATH", "ENV", "GLOBIGNORE", "IFS", "PATH", "POSIXLY_CORRECT",
                     "PS4", "SHELLOPTS"}
ENVIRONMENT_PREFIXES = ("BASH_FUNC_", "LD_", "DYLD_", "CARGO_BUILD_", "CARGO_TARGET_", "RUSTC", "PYTHON")


def plain_environment(*tables):
    """Whether no `env:` table sets a variable of SHELL_ENVIRONMENT or one that
    starts with one of ENVIRONMENT_PREFIXES."""
    return all(table is None or isinstance(table, dict) and not any(
        name in SHELL_ENVIRONMENT or name.startswith(ENVIRONMENT_PREFIXES) for name in table)
        for table in tables)


def run_steps(workflow):
    """(script, directory) of each `run:` step that every pull request runs and
    whose failure fails the job. Neither the step nor its job, nor any job that
    it needs, has `if:` or a `continue-on-error` that can be true; `unix_job`
    holds; the step uses bash; its script is a single line or a literal block;
    `plain_environment` holds for the workflow, job and step; and no earlier
    step of the job names GITHUB_ENV or GITHUB_PATH. A workflow outside the
    YAML subset yields nothing."""
    try:
        tree = yaml_load(workflow)
    except YamlError:
        return
    if not isinstance(tree, dict) or not every_pull_request(tree.get("on")):
        return
    def defaults(table):
        run = ((table.get("defaults") or {}) if isinstance(table.get("defaults"), dict) else {}).get("run")
        return run if isinstance(run, dict) else {}
    jobs = tree.get("jobs") if isinstance(tree.get("jobs"), dict) else {}
    def unconditional(name, seen=()):
        job = jobs.get(name)
        if not isinstance(job, dict) or name in seen or "if" in job or may_skip(job.get("continue-on-error")):
            return False
        needs = job.get("needs", [])
        needs = [needs] if isinstance(needs, str) else needs
        return isinstance(needs, list) and all(unconditional(need, seen + (name,)) for need in needs)
    top = defaults(tree)
    for name, job in jobs.items():
        if not unconditional(name) or not unix_job(job):
            continue
        settings, tainted = dict(top, **defaults(job)), False
        for step in job.get("steps") or []:
            script = step.get("run") if isinstance(step, dict) else None
            if not isinstance(script, str):
                continue
            countable = (not tainted and not isinstance(script, Folded) and "if" not in step
                         and not may_skip(step.get("continue-on-error"))
                         and step.get("shell", settings.get("shell")) in (None, "bash")
                         and plain_environment(tree.get("env"), job.get("env"), step.get("env")))
            tainted = tainted or "GITHUB_ENV" in script or "GITHUB_PATH" in script
            if countable:
                directory = step.get("working-directory", settings.get("working-directory", "."))
                yield script, shell_directory(PurePosixPath("."), str(directory))


PLAIN_WORD = r"(?:[A-Za-z0-9_./:=@%+,-]|'[^'\r\n]*')+"
PLAIN_LINE = re.compile(rf" *(?:{PLAIN_WORD}(?: +{PLAIN_WORD})*)?(?: *| +\\)")
PLAIN_COMMENT = re.compile(r" *(?:#.*)?")
# Bash reserved words and builtins. A plain command names none of them, except
# those in PLAIN_BUILTINS and `cd` and `set`, which the reader follows.
SHELL_WORDS = {
    "!", "[[", "]]", "{", "}", "case", "coproc", "do", "done", "elif", "else", "esac", "fi", "for", "function",
    "if", "in", "select", "then", "time", "until", "while", ".", ":", "[", "alias", "bg", "bind", "break",
    "builtin", "caller", "cd", "command", "compgen", "complete", "compopt", "continue", "declare", "dirs",
    "disown", "echo", "enable", "eval", "exec", "exit", "export", "false", "fc", "fg", "getopts", "hash", "help",
    "history", "jobs", "kill", "let", "local", "logout", "mapfile", "popd", "printf", "pushd", "pwd", "read",
    "readarray", "readonly", "return", "set", "shift", "shopt", "source", "suspend", "test", "times", "trap",
    "true", "type", "typeset", "ulimit", "umask", "unalias", "unset", "wait"}
PLAIN_BUILTINS = {":", "echo", "false", "pwd", "test", "true"}
SET_LETTERS = {"e": "errexit", "u": "nounset", "v": "verbose", "x": "xtrace"}
SET_OPTIONS = {"errexit", "nounset", "pipefail", "verbose", "xtrace"}
# In a script file, this line goes to the parent of the script's directory.
SCRIPT_PARENT = 'cd "$(dirname "$0")/.."'


def shell_directory(directory, target):
    """`directory / target`, or None when the result is unknown."""
    if directory is None or not target or target.startswith(("/", "~")) or any(c in target for c in "$`*?"):
        return None
    return PurePosixPath(os.path.normpath(str(directory / target)))


def plain_set(arguments):
    """The (on, option) switches of `set ARGUMENTS`, or None unless each
    argument switches options of SET_OPTIONS: `-e`, `-u`, `-v`, `-x`, and
    `-o` or `+o` before an option name."""
    switches, pending = [], []
    for argument in arguments:
        if pending:
            if argument not in SET_OPTIONS:
                return None
            switches.append((pending.pop(0), argument))
        elif len(argument) > 1 and argument[0] in "-+" and all(c in SET_LETTERS or c == "o" for c in argument[1:]):
            for letter in argument[1:]:
                if letter == "o":
                    pending.append(argument[0] == "-")
                else:
                    switches.append((argument[0] == "-", SET_LETTERS[letter]))
        else:
            return None
    return switches if switches and not pending else None


def plain_commands(script, directory=PurePosixPath("."), errexit=True, origin=None):
    """(words, directory, counted) for each command of a shell script before its
    first line that is not plain. A command counts when errexit is on, so that
    its failure fails the script.

    A plain line is blank, a comment, or words of letters, digits, `_./:=@%+,-`
    and single-quoted text, separated by spaces; a final ` \\` joins the next
    line. The first word of a command names a program or a member of
    PLAIN_BUILTINS, and has no `=`. `cd` with one relative directory is plain
    too: the reader follows it while errexit is on, and the directory becomes
    None, unknown, when it is off. So is `set` with switches that `plain_set`
    reads. `origin`, the directory of a script file, makes SCRIPT_PARENT plain."""
    words = []
    for line in script.split("\n"):
        if not words and PLAIN_COMMENT.fullmatch(line):
            continue
        if not words and origin is not None and line.strip() == SCRIPT_PARENT:
            directory = shell_directory(origin, "..") if errexit else None
            continue
        if not PLAIN_LINE.fullmatch(line):
            return
        words += [re.sub(r"'([^']*)'", r"\1", word) for word in re.findall(PLAIN_WORD, line)]
        if line.endswith("\\") or not words:
            continue
        switches = plain_set(words[1:]) if words[0] == "set" else None
        if words[0] == "cd" and len(words) == 2 and not words[1].startswith("-"):
            directory = shell_directory(directory, words[1]) if errexit else None
        elif switches is not None:
            errexit = {option: on for on, option in switches}.get("errexit", errexit)
        elif "=" not in words[0] and (words[0] in PLAIN_BUILTINS or words[0] not in SHELL_WORDS):
            yield words, directory, errexit
        else:
            return
        words = []


def option(argument, items, short, long):
    """The value of `-s VALUE`, `-sVALUE`, `--long VALUE` or `--long=VALUE`, or None."""
    if argument == short or long and argument == long:
        return next(items, "")
    if short and argument.startswith(short) and len(argument) > len(short) and not argument.startswith("--"):
        return argument[len(short):]
    if long and argument.startswith(long + "="):
        return argument[len(long) + 1:]
    return None


# The options of `cargo test` that the check reads. Any other option, such as
# --no-run, --doc, --help, --target or --config, runs no test as far as the
# check is concerned.
CARGO_FLAGS = {"--all", "--all-features", "--all-targets", "--benches", "--bins", "--examples", "--frozen",
               "--ignore-rust-version", "--keep-going", "--lib", "--locked", "--no-default-features", "--no-fail-fast",
               "--offline", "--quiet", "--release", "--tests", "--verbose", "--workspace", "-q", "-v", "-vv"}
CARGO_VALUES = {"--bench", "--bin", "--color", "--example", "--exclude", "--features", "--jobs", "--manifest-path",
                "--message-format", "--package", "--profile", "--target-dir", "--test", "-F", "-j", "-p"}
CARGO_TARGETS = {"--bench", "--benches", "--bin", "--bins", "--example", "--examples", "--lib"}
# The options of the libtest harness, after `--`, that the check reads. Any
# other option, such as --list, --help or --exclude-should-panic, runs no test.
LIBTEST_FLAGS = {"--exact", "--ignored", "--include-ignored", "--nocapture", "--quiet", "--show-output", "-q"}
LIBTEST_VALUES = {"--color", "--skip", "--test-threads"}


@dataclass
class CargoRun:
    every_test: bool
    targets: set
    ignored: str
    filters: list
    skips: list
    exact: bool
    runs_nothing: bool

    def runs(self, stem, name, ignored):
        if self.runs_nothing or not (self.every_test or stem in self.targets):
            return False
        if ignored and self.ignored == "exclude" or not ignored and self.ignored == "only":
            return False

        def matches(pattern):
            return name == pattern if self.exact else pattern in name

        if any(matches(skip) for skip in self.skips):
            return False
        return not self.filters or any(matches(item) for item in self.filters)


def cargo_run(arguments, package=None):
    """The tests that `cargo test ARGUMENTS` runs in the root package `package`.
    An option outside CARGO_FLAGS and CARGO_VALUES, or after `--` outside
    LIBTEST_FLAGS and LIBTEST_VALUES, makes it run nothing."""
    split = arguments.index("--") if "--" in arguments else len(arguments)
    run = CargoRun(False, set(), "exclude", [], [], False, False)
    selected = False

    def options(arguments, flags, values):
        """(name, value) for each option, with value None for a flag, or ("", word) for a positional word."""
        items = iter(arguments)
        for argument in items:
            name, equals, attached = argument.partition("=") if argument.startswith("--") else (argument, "", "")
            if name in values:
                value = attached if equals else next(items, None)
                if value is None:
                    run.runs_nothing = True
                    return
                yield name, value
            elif name in flags and not equals:
                yield name, None
            elif argument.startswith("-"):
                run.runs_nothing = True
            else:
                yield "", argument

    for name, value in options(arguments[:split], CARGO_FLAGS, CARGO_VALUES):
        if name in ("-p", "--package") and value != package or name == "--exclude" and value == package:
            run.runs_nothing = True
        elif name == "--manifest-path" and os.path.normpath(value) != "Cargo.toml":
            run.runs_nothing = True
        elif name in ("--all-targets", "--tests"):
            run.every_test = selected = True
        elif name == "--test":
            selected = True
            run.targets.add(value)
        elif name in CARGO_TARGETS:
            selected = True
        elif not name:
            run.filters.append(value)
    if not selected:
        run.every_test = True
    for name, value in options(arguments[split + 1:], LIBTEST_FLAGS, LIBTEST_VALUES):
        if name == "--skip":
            run.skips.append(value)
        elif name == "--ignored":
            run.ignored = "only"
        elif name == "--include-ignored":
            run.ignored = "include"
        elif name == "--exact":
            run.exact = True
        elif not name:
            run.filters.append(value)
    return run


@dataclass
class DiscoverRun:
    start: PurePosixPath
    pattern: str
    selections: list

    def runs(self, path, test_class, method):
        path = PurePosixPath(path)
        if path.parent != self.start or not fnmatch.fnmatchcase(path.name, self.pattern):
            return False
        full = f"{path.stem}.{test_class}.{method}"
        return not self.selections or any(
            fnmatch.fnmatchcase(full, item) if "*" in item else item in full for item in self.selections)


DISCOVER_FLAGS = {"--buffer", "--catch", "--failfast", "--locals", "--quiet", "--verbose", "-b", "-c", "-f", "-q",
                  "-v"}
DISCOVER_SHORT = {"-k": "select", "-p": "pattern", "-s": "start"}
DISCOVER_LONG = {"--durations": "durations", "--pattern": "pattern", "--start-directory": "start"}


def discover_run(arguments, directory):
    """The tests that `python3 -m unittest discover ARGUMENTS` runs from
    `directory`, or None. An option outside DISCOVER_FLAGS, DISCOVER_SHORT and
    DISCOVER_LONG gives None: `--help` runs no test, and a top-level directory
    `-t` changes the names that `-k` matches."""
    found, positional, selections = {"start": ".", "pattern": "test*.py"}, [], []
    items = iter(arguments)
    for argument in items:
        if argument in DISCOVER_FLAGS:
            continue
        if argument.startswith("--"):
            name, equals, attached = argument.partition("=")
            key, value = DISCOVER_LONG.get(name), attached if equals else None
        elif argument.startswith("-"):
            key, value = DISCOVER_SHORT.get(argument[:2]), argument[2:] or None
        else:
            positional.append(argument)
            continue
        value = value if value is not None else next(items, None)
        if key is None or value is None:
            return None
        if key == "select":
            selections.append(value)
        elif key != "durations":
            found[key] = value
    if len(positional) > 2:
        return None
    found.update(zip(("start", "pattern"), positional))
    resolved = shell_directory(directory, found["start"])
    return DiscoverRun(resolved, found["pattern"], selections) if resolved is not None else None


RUST_RAW = re.compile(r'(b?)r(#*)"')
RUST_CHAR = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]{1,6}\}|.)|[^\\'\n])'")
RUST_TOKEN = re.compile(r"#!?\[|\bmod\s+([A-Za-z_]\w*)\s*\{|\bfn\s+([A-Za-z_]\w*)|[{};]")
RUST_NAME = re.compile(r"\s*([A-Za-z_][\w:]*)")


def rust_blank(source):
    """The source without comments, with the contents of string and character
    literals removed. Newlines stay."""
    out, i, n = [], 0, len(source)

    def identifier_before(index):
        return index > 0 and (source[index - 1].isalnum() or source[index - 1] == "_")

    while i < n:
        if source.startswith("//", i):
            end = source.find("\n", i)
            i = n if end < 0 else end
            continue
        if source.startswith("/*", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if source.startswith("/*", i):
                    depth, i = depth + 1, i + 2
                elif source.startswith("*/", i):
                    depth, i = depth - 1, i + 2
                else:
                    out.append("\n" if source[i] == "\n" else "")
                    i += 1
            continue
        raw = RUST_RAW.match(source, i)
        if raw and not identifier_before(i):
            end = source.find('"' + raw.group(2), raw.end())
            end = n if end < 0 else end + 1 + len(raw.group(2))
            out.append('""' + "\n" * source.count("\n", i, end))
            i = end
            continue
        if source[i] == '"' or source.startswith('b"', i) and not identifier_before(i):
            j = i + (2 if source[i] == "b" else 1)
            while j < n and source[j] != '"':
                j += 2 if source[j] == "\\" else 1
            out.append('""' + "\n" * source.count("\n", i, j))
            i = j + 1
            continue
        if source[i] == "'":
            match = RUST_CHAR.match(source, i)
            if match:
                out.append("' '")
                i = match.end()
                continue
        out.append(source[i])
        i += 1
    return "".join(out)


def rust_closing(text, start):
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "[":
            depth += 1
        elif text[index] == "]":
            depth -= 1
            if depth == 0:
                return index
    return len(text) - 1


def rust_attribute(attribute):
    match = RUST_NAME.match(attribute)
    return match.group(1) if match else ""


def rust_conditional(attributes):
    """Whether attributes compile their item only under a configuration other
    than `cfg(test)`: a `cfg` attribute, or a `cfg_attr` that adds one."""
    return any(rust_attribute(a) == "cfg" and re.sub(r"\s", "", a) != "cfg(test)"
               or rust_attribute(a) == "cfg_attr" and re.search(r"\bcfg\s*\(", a[len("cfg_attr"):])
               for a in attributes)


def rust_tests(source):
    """Map the libtest name of each `#[test]` function, such as `a::b`, to
    (ignored, conditional). A test is ignored under `#[ignore]` or a `cfg_attr`
    that can add `ignore`. It is conditional under `#[cfg(...)]` other than
    `cfg(test)`, or a `cfg_attr` that adds one, on the function or on an
    enclosing module or file. A `#[test]` function inside another item, such
    as a function body, is no test: libtest does not collect it."""
    text = rust_blank(source)
    found, stack, pending, whole_file, index = {}, [], [], False, 0
    while True:
        match = RUST_TOKEN.search(text, index)
        if not match:
            return found
        token, index = match.group(0), match.end()
        if token.startswith("#"):
            end = rust_closing(text, match.end() - 1)
            body, index = text[match.end():end], end + 1
            if token != "#![":
                pending.append(body)
            elif rust_conditional([body]):
                if stack:
                    stack[-1] = (stack[-1][0], stack[-1][1], True)
                else:
                    whole_file = True
            continue
        if match.group(1):
            stack.append((True, match.group(1), rust_conditional(pending)))
        elif match.group(2):
            if all(frame[0] for frame in stack) and any(re.sub(r"\s", "", a) == "test" for a in pending):
                path = "::".join([frame[1] for frame in stack if frame[0]] + [match.group(2)])
                ignored = any(rust_attribute(a) == "ignore"
                              or rust_attribute(a) == "cfg_attr" and re.search(r"\bignore\b", a) for a in pending)
                found[path] = (bool(ignored),
                               whole_file or any(frame[2] for frame in stack) or rust_conditional(pending))
        elif token == "{":
            stack.append((False, None, rust_conditional(pending)))
        elif token == "}" and stack:
            stack.pop()
        pending = []


# Names whose use in a module may keep unittest from running its test methods
# as written, or make a failure pass.
PYTHON_SKIPS = {"SkipTest", "__unittest_expecting_failure__", "__unittest_skip__", "expectedFailure", "load_tests",
                "skip", "skipIf", "skipTest", "skipUnless"}


def python_skips(source):
    """Whether a module names a member of PYTHON_SKIPS anywhere, in any use."""
    return any(isinstance(node, ast.Name) and node.id in PYTHON_SKIPS
               or isinstance(node, ast.Attribute) and node.attr in PYTHON_SKIPS
               or isinstance(node, ast.alias) and node.name.split(".")[-1] in PYTHON_SKIPS
               or isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name in PYTHON_SKIPS
               for node in ast.walk(ast.parse(source)))


def python_tests(source):
    """(class, method) of the test methods of the unittest.TestCase classes of a
    module, mapped to whether unittest may skip them or expect them to fail.
    It may whenever `python_skips` holds for the module, whatever the condition
    or the class that the name concerns, and for an `async def` method of a
    class that is no IsolatedAsyncioTestCase, which unittest never awaits."""
    module = ast.parse(source)
    classes = {node.name: node for node in module.body if isinstance(node, ast.ClassDef)}

    def base_names(node):
        return [base.attr if isinstance(base, ast.Attribute) else getattr(base, "id", "") for base in node.bases]

    def test_case(name, kinds=("TestCase", "IsolatedAsyncioTestCase"), seen=()):
        node = classes.get(name)
        return node is not None and name not in seen and any(
            base in kinds or test_case(base, kinds, seen + (name,)) for base in base_names(node))

    def methods(name, seen=()):
        """Each test method of the class, mapped to whether it is `async def`."""
        node = classes.get(name)
        if node is None or name in seen:
            return {}
        found = {}
        for base in reversed(base_names(node)):
            found.update(methods(base, seen + (name,)))
        for item in node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name.startswith("test"):
                found[item.name] = isinstance(item, ast.AsyncFunctionDef)
        return found

    skips = python_skips(source)
    return {(name, method): skips or asynchronous and not test_case(name, ("IsolatedAsyncioTestCase",))
            for name in classes if test_case(name) for method, asynchronous in methods(name).items()}


class Repository:
    """The tests, the CI steps, the kernel regressions and the diagnostic codes of a checkout."""

    def __init__(self, root):
        self.root = root
        self.cargo, self.discover, self.regression_steps = [], [], 0
        package, manifest = None, {}
        if (root / "Cargo.toml").is_file():
            try:
                manifest = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))
            except tomllib.TOMLDecodeError:
                manifest = {}
            package = manifest.get("package", {}).get("name")
        # Integration tests that cargo builds by itself, with the libtest harness
        # and no required features: those of tests/*.rs, unless autotests is off or
        # a [[test]] target names the file.
        targets = manifest.get("test", [])
        self.autotests = manifest.get("package", {}).get("autotests", True) is not False
        self.listed = {os.path.normpath(target.get("path", f"tests/{target.get('name')}.rs"))
                       for target in (targets if isinstance(targets, list) else []) if isinstance(target, dict)}
        if not isinstance(targets, list):
            self.autotests = False
        directory = root / WORKFLOWS
        workflows = sorted(directory.glob("*.yml")) + sorted(directory.glob("*.yaml")) if directory.is_dir() else []
        for path in workflows:
            for script, start in run_steps(path.read_text(encoding="utf-8")):
                for words, where, counted in plain_commands(script, start):
                    if counted:
                        self.add(words, where, package)
        self.regressions = set()
        if (root / REGRESSIONS).is_file():
            # Bash runs the script as `bash SCRIPT`: errexit is off, and only "\n" ends a line.
            with open(root / REGRESSIONS, encoding="utf-8", newline="") as handle:
                script = handle.read()
            for words, where, counted in plain_commands(script, errexit=False, origin=PurePosixPath(REGRESSIONS).parent):
                if counted and where == PurePosixPath(".") and words[:4] == ["lake", "-d", "lean-kernel", "build"] \
                        and all(LEAN_NAME.fullmatch(item) for item in words[4:]):
                    self.regressions.update(words[4:])
        self.codes = set()
        if (root / DIAGNOSTICS).is_file():
            self.codes = set(re.findall(r"`(E_[A-Z0-9_]+)`", (root / DIAGNOSTICS).read_text(encoding="utf-8")))
        self._rust, self._python = {}, {}

    def add(self, words, directory, package):
        """Record a plain command that runs Rust tests, Python tests or the regression script."""
        if words[:2] == ["cargo", "test"]:
            if directory == PurePosixPath("."):
                self.cargo.append(cargo_run(words[2:], package))
        elif words[0] in ("python", "python3") and words[1:4] == ["-m", "unittest", "discover"]:
            run = discover_run(words[4:], directory) if directory is not None else None
            if run is not None:
                self.discover.append(run)
        elif words[0] == "bash" and len(words) == 2 and shell_directory(directory, words[1]) == PurePosixPath(REGRESSIONS):
            self.regression_steps += 1

    def rust(self, path):
        if path not in self._rust:
            file = self.root / path
            self._rust[path] = rust_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
        return self._rust[path]

    def python(self, path):
        if path not in self._python:
            file = self.root / path
            try:
                self._python[path] = python_tests(file.read_text(encoding="utf-8")) if file.is_file() else None
            except SyntaxError:
                self._python[path] = None
        return self._python[path]

    def package_skips(self, path):
        """Whether an `__init__.py` of a package that contains the module at `path` names a member of PYTHON_SKIPS."""
        for directory in PurePosixPath(path).parents:
            init = self.root / directory / "__init__.py"
            try:
                if init.is_file() and python_skips(init.read_text(encoding="utf-8")):
                    return True
            except SyntaxError:
                return True
        return False

    def check_test(self, item, where, errors):
        """Check one Tested reference: the test exists and a CI step runs it."""
        if match := RUST_TEST.fullmatch(item):
            path, name = match.groups()
            tests = self.rust(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist")
            elif name not in tests:
                errors.append(f"{where}: {path} has no #[test] function `{name}`")
            elif tests[name][1]:
                errors.append(f"{where}: `{item}` is compiled only under a #[cfg(...)] condition, "
                              "so it does not count as run")
            elif not self.autotests or os.path.normpath(path) in self.listed:
                errors.append(f"{where}: Cargo.toml sets `autotests = false` or lists {path} under [[test]], "
                              f"so `{item}` does not count as run")
            elif not any(run.runs(PurePosixPath(path).stem, name, tests[name][0]) for run in self.cargo):
                if tests[name][0]:
                    errors.append(f"{where}: `{item}` is #[ignore]d, and no CI step passes --ignored for it")
                else:
                    errors.append(f"{where}: no CI step runs `{item}`")
        elif match := PYTHON_TEST.fullmatch(item):
            path, test_class, method = match.groups()
            tests = self.python(path)
            if tests is None:
                errors.append(f"{where}: the test file {path} does not exist or does not parse")
            elif (test_class, method) not in tests:
                errors.append(f"{where}: {path} has no unittest test method `{test_class}.{method}`")
            elif tests[(test_class, method)] or self.package_skips(path):
                errors.append(f"{where}: unittest may skip `{item}` or expect it to fail")
            elif not any(run.runs(path, test_class, method) for run in self.discover):
                errors.append(f"{where}: no CI step runs `{item}`")
        elif LEAN_NAME.fullmatch(item):
            if item not in self.regressions:
                errors.append(f"{where}: `{item}` is not a module that {REGRESSIONS} builds")
            elif not module_source(self.root, item):
                errors.append(f"{where}: the regression module `{item}` has no source file")
            elif not self.regression_steps:
                errors.append(f"{where}: no CI step runs {REGRESSIONS}")
        else:
            errors.append(f"{where}: `{item}` is not a test reference: use tests/<file>.rs::<function>, "
                          "<directory>/test_<name>.py::<Class>::<method> or a kernel regression module")

    def tested_form(self, item):
        return bool(RUST_TEST.fullmatch(item) or PYTHON_TEST.fullmatch(item) or item in self.regressions)


def module_path(module):
    top = module.split(".", 1)[0]
    if top not in SOURCES:
        return None
    return PurePosixPath(SOURCES[top], *module.split(".")).with_suffix(".lean")


def module_source(root, module):
    path = module_path(module)
    return path is not None and (root / path).is_file()


# Statement pins.

def load_pins(root, environment, errors):
    path = PINS / f"{environment}.json"
    if not (root / path).exists():
        return {}
    try:
        data = json.loads((root / path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        errors.append(f"{path}: cannot read: {error}")
        return {}
    rules = ENVIRONMENTS[environment]
    if not isinstance(data, dict) or set(data) != {"format", "environment", "imports", "entries"} \
            or data.get("format") != 1 or data.get("environment") != environment \
            or not isinstance(data.get("imports"), list) or not isinstance(data.get("entries"), list):
        errors.append(f"{path}: expected format 1 with `environment` {environment!r}, `imports` and `entries`")
        return {}
    pins, names, modules = {}, [], set()
    for index, entry in enumerate(data["entries"]):
        where = f"{path} entries[{index}]"
        kind = entry.get("kind") if isinstance(entry, dict) else None
        expected = {"name", "module", "kind", "statement"} if kind == "theorem" else {"name", "module", "kind"}
        if not isinstance(entry, dict) or kind not in ("theorem", "definition") or set(entry) != expected \
                or not all(isinstance(entry[key], str) for key in expected):
            errors.append(f"{where}: expected a theorem with `name`, `module`, `kind` and `statement`, "
                          "or a definition with `name`, `module` and `kind`")
            continue
        name, module = entry["name"], entry["module"]
        root_name = rules["theorems"] if kind == "theorem" else rules["definitions"]
        if root_name is None:
            errors.append(f"{where}: the {environment} environment resolves no kernel definitions")
            continue
        if not LEAN_NAME.fullmatch(name) or not name.startswith(root_name + "."):
            errors.append(f"{where}: `{name}` is not a fully qualified name under {root_name}")
        if not LEAN_NAME.fullmatch(module) or not module.startswith(root_name + "."):
            errors.append(f"{where}: the module `{module}` of `{name}` is not under {root_name}")
        elif not module_source(root, module):
            errors.append(f"{where}: the module `{module}` of `{name}` has no source file {module_path(module)}")
        if kind == "theorem" and not STATEMENT.fullmatch(entry["statement"]):
            errors.append(f"{where}: `statement` must be sha256: followed by 64 lower-case hex digits")
        if name in pins:
            errors.append(f"{where}: `{name}` is pinned twice")
        pins[name], modules = entry, modules | {module}
        names.append(name)
    if names != sorted(names):
        errors.append(f"{path}: entries must be sorted by name")
    if data["imports"] != sorted(modules):
        errors.append(f"{path}: `imports` must list exactly the pinned modules, sorted")
    return pins


def format_pins(environment, entries):
    lines = ["{", '  "format": 1,', f'  "environment": {json.dumps(environment)},']
    modules = sorted({entry["module"] for entry in entries})
    lines.append('  "imports": [' + ("" if modules else "],"))
    lines += [f"    {json.dumps(m)}{',' if i + 1 < len(modules) else ''}" for i, m in enumerate(modules)]
    if modules:
        lines.append("  ],")
    lines.append('  "entries": [' + ("" if entries else "]"))
    for index, entry in enumerate(entries):
        keys_in_order = ["name", "module", "kind"] + (["statement"] if entry["kind"] == "theorem" else [])
        body = ", ".join(f"{json.dumps(key)}: {json.dumps(entry[key], ensure_ascii=False)}"
                         for key in keys_in_order)
        lines.append(f"    {{{body}}}{',' if index + 1 < len(entries) else ''}")
    if entries:
        lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


# Loading and checking.

def load(root, errors, pin_errors=None):
    """Parse and check every specification file. Errors about the statement pins
    go to `pin_errors` when it is given, so that an update can ignore them."""
    pin_errors = errors if pin_errors is None else pin_errors
    repository = Repository(root)
    registry = parse_registry(root, errors)
    specs, owners = [], {}
    directory = root / SPEC
    files = sorted(directory.glob("*.toml")) if directory.is_dir() else []
    for file in files:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path == REGISTRY:
            continue
        spec = parse_spec(root, path, errors)
        if spec:
            specs.append(spec)
    file_ids = {}
    for spec in specs:
        if spec.id in file_ids:
            errors.append(f"{spec.path}: the file id `{spec.id}` is also used by {file_ids[spec.id]}")
        file_ids[spec.id] = spec.path
        for item in spec.properties:
            if item.id in owners:
                errors.append(f'{spec.path} [property."{item.id}"]: duplicate property id; '
                              f"{owners[item.id]} defines it too")
            owners[item.id] = spec.path
    cited = {environment: {} for environment in ENVIRONMENTS}
    for spec in specs:
        for item in spec.properties:
            where = f'{spec.path} [property."{item.id}"]'
            if item.example_test:
                repository.check_test(item.example_test, f"{where} example_test", errors)
            for claim in item.claims:
                check_claim(claim, f"{where} claim.{claim.name}", repository, registry, cited, errors)
    pins = {environment: load_pins(root, environment, pin_errors) for environment in ENVIRONMENTS}
    for environment, names in cited.items():
        path = PINS / f"{environment}.json"
        update = f"run `python3 scripts/check_spec.py --update-statements {environment}`"
        if not names:
            if (root / path).exists():
                pin_errors.append(f"{path}: no claim cites a name of the {environment} environment; "
                                  "delete this file and the CI step that resolves it")
            continue
        for name, kinds in sorted(names.items()):
            pin = pins[environment].get(name)
            if pin is None:
                pin_errors.append(f"{path}: `{name}` is cited but not pinned; {update}")
            elif pin["kind"] not in kinds:
                pin_errors.append(f"{path}: `{name}` is cited as a {next(iter(kinds))} but pinned as a {pin['kind']}")
        for name in sorted(pins[environment].keys() - names.keys()):
            pin_errors.append(f"{path}: `{name}` is pinned but no claim cites it; {update}")
    outputs = {spec.chapter: render_spec(spec, pins, registry) for spec in specs}
    if registry or (root / REGISTRY).exists():
        outputs[REGISTRY.with_suffix(".md")] = render_registry(registry, specs)
    return State(specs, registry, pins, cited, outputs)


def check_claim(claim, where, repository, registry, cited, errors):
    if claim.status in PROVED:
        environment = PROVED[claim.status]
        root_name = ENVIRONMENTS[environment]["theorems"]
        for item in claim.evidence:
            if repository.tested_form(item):
                errors.append(f"{where}: `{item}` is Tested evidence; a {STATUSES[claim.status]} claim "
                              f"cites theorems under {root_name}")
            elif not LEAN_NAME.fullmatch(item) or not item.startswith(root_name + "."):
                errors.append(f"{where}: `{item}` is not a fully qualified theorem name under {root_name}")
            else:
                cited[environment].setdefault(item, set()).add("theorem")
    elif claim.status == "tested":
        for item in claim.evidence:
            repository.check_test(item, where, errors)
    elif claim.status == "assumed":
        for item in claim.evidence:
            if item not in registry:
                errors.append(f"{where}: unknown assumption `{item}`; {REGISTRY} lists the assumptions")
    for item in claim.assumes:
        if item not in registry:
            errors.append(f"{where}: unknown assumption `{item}` in `assumes`; {REGISTRY} lists the assumptions")
    for definition, code in claim.enforced_by:
        if definition:
            cited["oracle"].setdefault(definition, set()).add("definition")
        if code and code not in repository.codes:
            errors.append(f"{where}: unknown diagnostic code `{code}`; {DIAGNOSTICS} lists every code")


def check(root):
    errors = []
    state = load(root, errors)
    for path, expected in state.outputs.items():
        file = root / path
        if not file.is_file() or file.read_text(encoding="utf-8") != expected:
            errors.append(f"{path}: out of date; run `python3 scripts/check_spec.py --write`")
    directory = root / SPEC
    for file in sorted(directory.glob("*.md")) if directory.is_dir() else []:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path not in state.outputs:
            errors.append(f"{path}: no spec file generates this chapter")
    summary = (root / SUMMARY).read_text(encoding="utf-8") if (root / SUMMARY).is_file() else ""
    for path in state.outputs:
        link = path.relative_to("docs").as_posix()
        if f"]({link})" not in summary:
            errors.append(f"{SUMMARY}: does not list the generated chapter {link}")
    return errors, state


def write(root, state):
    for path, contents in state.outputs.items():
        (root / path).write_text(contents, encoding="utf-8")
    directory = root / SPEC
    for file in sorted(directory.glob("*.md")) if directory.is_dir() else []:
        path = PurePosixPath(file.relative_to(root).as_posix())
        if path not in state.outputs and MARKER in file.read_text(encoding="utf-8"):
            file.unlink()


# Chapters.

def link_module(module):
    path = module_path(module)
    return f"[`{module}`]({BLOB}{path})" if path else f"`{module}`"


def assumption_link(identifier, registry):
    entry = registry.get(identifier)
    title = entry.title if entry else identifier
    return f"[{title}](assumptions.md#assumption.{identifier})"


def test_reference(item):
    if match := RUST_TEST.fullmatch(item):
        return f"`{match.group(2)}` in [`{match.group(1)}`]({BLOB}{match.group(1)})"
    if match := PYTHON_TEST.fullmatch(item):
        return f"`{match.group(2)}.{match.group(3)}` in [`{match.group(1)}`]({BLOB}{match.group(1)})"
    return f"{link_module(item)}, built by [`{REGRESSIONS}`]({BLOB}{REGRESSIONS})"


def lean_evidence(names, pins):
    groups = {}
    for name in names:
        pin = pins.get(name)
        groups.setdefault(pin["module"] if pin else None, []).append(name)
    lines = []
    for module, members in groups.items():
        listed = ", ".join(f"`{name}`" for name in members)
        lines.append(f"{link_module(module)}: {listed}" if module else f"not pinned: {listed}")
    return lines


def claim_lines(claim, pins, registry):
    lines = [f"- `{claim.name}`: [{STATUSES[claim.status]}](../specifications.md#{claim.status})"]
    if claim.status in PROVED:
        lines.append("  - Evidence:")
        lines += [f"    - {line}" for line in lean_evidence(claim.evidence, pins[PROVED[claim.status]])]
    elif claim.status == "tested":
        lines.append("  - Evidence:")
        lines += [f"    - {test_reference(item)}" for item in claim.evidence]
    elif claim.status == "assumed":
        lines.append("  - Evidence: " + ", ".join(assumption_link(item, registry) for item in claim.evidence))
    if claim.premises is not None:
        if claim.premises:
            lines.append("  - Premises:")
            lines += [f"    - {inline(premise)}" for premise in claim.premises]
        else:
            lines.append("  - Premises: none")
    if claim.assumes:
        lines.append("  - Assumes: " + ", ".join(assumption_link(item, registry) for item in claim.assumes))
    for definition, code in claim.enforced_by:
        pin = pins["oracle"].get(definition) if definition else None
        where = f" in {link_module(pin['module'])}" if pin else ""
        lines.append(f"  - Enforced by: `{definition}`{where}, which reports `{code}`")
    if claim.reason:
        lines.append(f"  - Reason: {inline(claim.reason)}")
    if claim.issue:
        lines.append(f"  - Issue: [#{claim.issue}]({ISSUES}{claim.issue})")
    if claim.note:
        lines.append(f"  - Note: {inline(claim.note)}")
    return lines


def render_spec(spec, pins, registry):
    lines = [f"# {spec.title}", "",
             f"{MARKER} from {spec.path}. Edit that file and run `python3 scripts/check_spec.py --write`. -->",
             "", inline(spec.description), "",
             f"[Specifications](../specifications.md) defines the "
             f"[claim statuses](../specifications.md#claim-statuses) and the checks. This chapter is "
             f"generated from [`{spec.path}`]({BLOB}{spec.path}).", "",
             "| Property | Claims |", "| --- | --- |"]
    for item in spec.properties:
        lines.append(f"| [{item.title}](#{item.id}) | "
                     f"{', '.join(STATUSES[claim.status] for claim in item.claims)} |")
    for item in spec.properties:
        label, target = item.rule
        lines += ["", f'<a id="{item.id}"></a>', "", f"## {item.title}", "",
                  f"- Property: `{item.id}`", f"- Subject: `{item.subject}`",
                  f"- Rule: [{label}](../{target})", "", inline(item.statement), "",
                  f"- Example: {inline(item.example)}"]
        if item.example_test:
            lines.append(f"- Run by: {test_reference(item.example_test)}")
        elif item.example_not_executed:
            lines.append(f"- Not executed: {inline(item.example_not_executed)}")
        lines += ["", "Claims:", ""]
        for claim in item.claims:
            lines += claim_lines(claim, pins, registry)
    return "\n".join(lines) + "\n"


def render_registry(registry, specs):
    citations = {identifier: [] for identifier in registry}
    for spec in specs:
        for item in spec.properties:
            for claim in item.claims:
                used = (claim.evidence if claim.status == "assumed" else []) + claim.assumes
                for identifier in dict.fromkeys(used):
                    if identifier in citations:
                        citations[identifier].append(
                            f"[`{item.id}`]({spec.chapter.name}#{item.id}) (`{claim.name}`)")
    lines = ["# Assumptions", "",
             f"{MARKER} from {REGISTRY}. Edit that file and run `python3 scripts/check_spec.py --write`. -->",
             "", "The assumption registry lists the trusted components that claims rest on. A claim with "
             "status [Assumed](../specifications.md#assumed) cites an entry as its evidence. A Proved or "
             "Tested claim lists in `assumes` the entries that relate its evidence to the property as the "
             f"statement reads it. This chapter is generated from [`{REGISTRY}`]({BLOB}{REGISTRY}).", "",
             "| Assumption | Claims that cite it |", "| --- | --- |"]
    for identifier, entry in registry.items():
        lines.append(f"| [{entry.title}](#assumption.{identifier}) | {len(citations[identifier])} |")
    for identifier, entry in registry.items():
        lines += ["", f'<a id="assumption.{identifier}"></a>', "", f"## {entry.title}", "",
                  f"- Assumption: `{identifier}`", "", inline(entry.statement), ""]
        if citations[identifier]:
            lines.append("Cited by:")
            lines.append("")
            lines += [f"- {citation}" for citation in citations[identifier]]
        else:
            lines.append("No claim cites this assumption.")
    return "\n".join(lines) + "\n"


# Statement pins from the Lean resolver.

def update_statements(root, environment):
    blocking = []
    state = load(root, blocking, pin_errors=[])
    if blocking:
        print("\n".join(blocking), file=sys.stderr)
        print("fix these errors before updating the statement pins", file=sys.stderr)
        return 1
    names = state.cited[environment]
    path = root / PINS / f"{environment}.json"
    if not names:
        if path.exists():
            path.unlink()
            print(f"removed {path.relative_to(root)}: no claim cites a name of the {environment} environment; "
                  "remove the CI step that resolves it")
        return 0
    rules = ENVIRONMENTS[environment]
    request = {"format": 1, "environment": environment, "imports": rules["discover"],
               "entries": [{"name": name, "kind": next(iter(kinds))} for name, kinds in sorted(names.items())]}
    with tempfile.TemporaryDirectory(prefix="vastitas-spec-") as directory:
        source, report = Path(directory) / "request.json", Path(directory) / "report.json"
        source.write_text(json.dumps(request), encoding="utf-8")
        try:
            result = subprocess.run(
                ["lake", "env", "lean", "-DwarningAsError=true", str(root / RESOLVER)],
                cwd=root / rules["directory"], text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                env=dict(os.environ, VASTITAS_SPEC_INPUT=str(source), VASTITAS_SPEC_REPORT=str(report)),
                check=False)
        except OSError as error:
            print(f"cannot run lake in {rules['directory']}/: {error}", file=sys.stderr)
            return 1
        try:
            facts = json.loads(report.read_text(encoding="utf-8")) if report.is_file() else None
        except ValueError:
            facts = None
    if not isinstance(facts, dict) or not isinstance(facts.get("entries"), list):
        print(result.stdout, file=sys.stderr)
        print(f"the resolver wrote no report in {rules['directory']}/; build that package first, "
              f"so that {', '.join(rules['discover'])} can be imported", file=sys.stderr)
        return 1
    if facts.get("problems") or result.returncode:
        print("\n".join(facts.get("problems") or [result.stdout]), file=sys.stderr)
        return 1
    entries = sorted(({key: entry[key] for key in ("name", "module", "kind", "statement") if key in entry}
                      for entry in facts["entries"]), key=lambda entry: entry["name"])
    old = state.pins[environment]
    for entry in entries:
        before = old.get(entry["name"])
        if before is None:
            print(f"pinned {entry['name']}")
        elif before != entry:
            print(f"changed {entry['name']}: review its statement and module")
    for name in sorted(old.keys() - {entry["name"] for entry in entries}):
        print(f"removed {name}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_pins(environment, entries), encoding="utf-8")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the chapters under docs/spec/")
    group.add_argument("--update-statements", choices=sorted(ENVIRONMENTS), metavar="ENVIRONMENT",
                       help="rewrite docs/spec/pins/ENVIRONMENT.json from the built Lean package")
    arguments = parser.parse_args(argv)
    if arguments.update_statements and update_statements(ROOT, arguments.update_statements):
        return 1
    if arguments.write or arguments.update_statements:
        write(ROOT, load(ROOT, []))
    errors, state = check(ROOT)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    properties = sum(len(spec.properties) for spec in state.specs)
    claims = sum(len(item.claims) for spec in state.specs for item in spec.properties)
    pinned = ", ".join(f"{len(state.pins[environment])} {environment}" for environment in ENVIRONMENTS)
    print(f"Specifications: {len(state.specs)} files, {properties} properties and {claims} claims; "
          f"statement pins: {pinned}; every generated chapter is fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
