#!/usr/bin/env python3
"""Generate the grammar summary of the book from the Syntax blocks of the Vastitas Reference.

    python3 scripts/grammar_summary.py           check that the chapter is fresh
    python3 scripts/grammar_summary.py --write   regenerate docs/appendix/grammar.md

The chapter holds the productions as text in plain code blocks. It has no
Syntax block of its own, so `scripts/check_book.py` counts no production of it
as a definition.
"""

import argparse
import re
import sys
from pathlib import Path

from book_markdown import PRODUCTION, expected_title, outside_code, read_contents, syntax_blocks


ROOT = Path(__file__).resolve().parents[1]
CHAPTER = "appendix/grammar.md"
COMMAND = "python3 scripts/grammar_summary.py --write"
MARKER = "<!-- Generated by scripts/grammar_summary.py"
# The Syntax block of this chapter illustrates the notation and defines nothing.
ILLUSTRATION = "language/notation.md"
HEADING = re.compile(r"^(#{1,6}) (.+?)\s*$")


def heading_text(title):
    """The text of a heading as mdBook renders it: without code and emphasis marks and link targets."""
    title = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", title)
    return re.sub(r"[`*]", "", title).strip()


def heading_id(text, used):
    """The id that mdBook gives a heading, with a counter after a repeated id."""
    base = "".join(ch.lower() if ch.isalnum() or ch in "_-" else "-" if ch.isspace() else "" for ch in text)
    count = used.get(base, 0)
    used[base] = count + 1
    return base if count == 0 else f"{base}-{count}"


def chapter_blocks(text):
    """Yield (section title, section id, lines) for each Syntax block of a chapter, in order.

    The section is the nearest heading above the block, and both are None for a
    block that stands under the title of the chapter. The title is the heading
    as the chapter writes it. The lines are the productions as the chapter
    writes them, with their continuation lines.
    """
    used = {}
    sections = []
    for number, line in outside_code(text.splitlines()):
        heading = HEADING.match(line)
        if heading:
            sections.append((number, len(heading[1]), heading[2], heading_id(heading_text(heading[2]), used)))
    for start, _, body in syntax_blocks(text):
        above = [section for section in sections if section[0] < start and section[1] > 1]
        title, anchor = (above[-1][2], above[-1][3]) if above else (None, None)
        yield title, anchor, body


def render(source, chapters):
    """The text of the grammar summary for the chapters of a book."""
    listed = {chapter.path: chapter for chapter in chapters}
    if CHAPTER not in listed:
        raise ValueError(f"SUMMARY.md does not list {CHAPTER}")
    up = "../" * CHAPTER.count("/")
    title = expected_title(listed[CHAPTER])
    out = [
        f"# {title}",
        "",
        f"{MARKER} from the Syntax blocks of the Vastitas Reference.",
        f"     Edit the chapter of the construct and run `{COMMAND}`. -->",
        "",
        "This appendix collects the productions of the Syntax blocks of the Vastitas",
        "Reference, by chapter and in the order of the Reference.",
        f"[Notation]({up}language/notation.md#grammar) explains how to read a production.",
        "The section that a group links holds the description and the rules of the",
        "construct. The appendix is generated from those sections. It defines no",
        "nonterminal and adds no rule.",
        "",
    ]
    count = 0
    for chapter in chapters:
        if chapter.part != "reference" or chapter.path == ILLUSTRATION:
            continue
        blocks = list(chapter_blocks((source / chapter.path).read_text(encoding="utf-8")))
        if not blocks:
            continue
        out += [f"## {chapter.title}", "", f"Chapter: [{chapter.title}]({up}{chapter.path}).", ""]
        for section, anchor, body in blocks:
            if section:
                out += [f"[{section}]({up}{chapter.path}#{anchor}):", ""]
            out += ["```text", *body, "```", ""]
            count += sum(1 for line in body if PRODUCTION.match(line))
    return "\n".join(out), count


def errors(source, chapters):
    """Return the reasons why the grammar summary of a book is not fresh."""
    target = source / CHAPTER
    try:
        expected, _ = render(source, chapters)
    except ValueError as error:
        return [str(error)]
    if not target.is_file():
        return [f"{CHAPTER}: missing; run `{COMMAND}`"]
    if target.read_text(encoding="utf-8") != expected:
        return [f"{CHAPTER}: out of date; run `{COMMAND}`"]
    return []


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help=f"regenerate docs/{CHAPTER}")
    arguments = parser.parse_args(argv)
    source = ROOT / "docs"
    chapters = read_contents(source)
    if arguments.write:
        text, count = render(source, chapters)
        (source / CHAPTER).write_text(text, encoding="utf-8")
        print(f"Wrote docs/{CHAPTER} with {count} productions")
        return 0
    problems = errors(source, chapters)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(f"docs/{CHAPTER} is fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
