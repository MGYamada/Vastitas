#!/usr/bin/env python3
"""Render package visibility/imports around the canonical flat stdlib sources.

No body rewriting: package mode uses the same arithmetic definitions and the
ordinary namespace checker. Run --check in CI; run without it after source edits.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "// Generated by scripts/sync_stdlib_package.py; edit stdlib/src/arithmetic/.\n"
IMPORTS = """use super::integers::int_add;
use super::integers::int_max;
use super::naturals::nat_add;
use super::naturals::nat_max;

"""


def rendered(name):
    source = (ROOT / "stdlib/src/arithmetic" / f"{name}.vast").read_text()
    public = "\n".join(
        "pub " + line if line.startswith(("fn ", "generic ")) else line
        for line in source.splitlines()
    ) + "\n"
    return HEADER + (IMPORTS if name == "generic" else "") + public


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for source, module in [("int", "integers"), ("nat", "naturals"), ("generic", "generic")]:
        path = ROOT / "stdlib/package/arithmetic" / f"{module}.vast"
        expected = rendered(source)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run scripts/sync_stdlib_package.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
